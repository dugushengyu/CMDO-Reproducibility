            if ~ismember(need{i},U10.Properties.VariableNames)

                error( ...
                    'U10 table missing field: %s', ...
                    need{i});

            end

        end

        ds = string(U10.dataset);
        bg = double(U10.budget);

        order = [];

        dsOrder = ["georgia","cpsc_2018"];

        for d = 1:numel(dsOrder)

            idx = find(ds==dsOrder(d));

            [~,o] = sort(bg(idx),'ascend');

            order = [order; idx(o)]; %#ok<AGROW>

        end

        U10 = U10(order,:);

        x_adapt = ...
            double(U10.shared_adaptive_gain_pct(:))';

        x_fixed = ...
            double(U10.shared_constant_mean_gain_pct(:))';

        state_labels = ...
            cell(1,height(U10));

        for i = 1:height(U10)

            if string(U10.dataset(i))=="georgia"
                cohort = 'Georgia';
            else
                cohort = 'CPSC';
            end

            state_labels{i} = ...
                sprintf( ...
                    '%s %d', ...
                    cohort, ...
                    double(U10.budget(i)));

        end

    end

    gatePath = fullfile( ...
        repoRoot, ...
        'U10_Prospective_ECG', ...
        '01_Prospective_Result', ...
        'U10_PRIMARY_RESULT.json');

    if isfile(gatePath)

        J = jsondecode(fileread(gatePath));

        if isfield(J,'primary_verdict')

            gateText = ...
                strrep( ...
                    char(string(J.primary_verdict)), ...
                    '_',' ');

        end

