function repoRoot = local_find_cmdo_repo(scriptDir)

repoRoot = '';

starts = {scriptDir,pwd};

for s = 1:numel(starts)

    p = starts{s};

    for k = 1:8

        if isempty(p)
            break;
        end

        if isfolder(fullfile(p,'U10_Prospective_ECG'))

            repoRoot = p;
            return;

        end

        parent = fileparts(p);

        if strcmp(parent,p)
            break;
        end

        p = parent;

    end

end

home = ...
    strtrim(getenv('USERPROFILE'));

if isempty(home)
    home = strtrim(getenv('HOME'));
end

if ~isempty(home)

    candidates = { ...
        fullfile(home,'CMDO-Reproducibility'), ...
        fullfile(home,'Documents','CMDO-Reproducibility'), ...
        fullfile(home,'Desktop','CMDO-Reproducibility')};

    for i = 1:numel(candidates)

        if isfolder( ...
                fullfile( ...
                    candidates{i}, ...
                    'U10_Prospective_ECG'))

            repoRoot = candidates{i};
            return;

        end

    end

end

