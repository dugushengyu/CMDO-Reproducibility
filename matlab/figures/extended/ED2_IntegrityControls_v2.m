function ED2_IntegrityControls_v2(outputDir, repoRoot)
% ED2_INTEGRITYCONTROLS_V2
%
% Extended Data Figure 2
% Role separation localizes a coupling pathway but incurs finite-audit cost.
%
% Scientific role after main-figure reorganization:
%
%   A  Role separation isolates decision and evaluation
%   B  Role separation suppresses coupling signatures
%   C  Role separation carries a finite-audit cost
%   D  Locked external mechanism challenge
%
% Main Fig. 5 establishes PRESERVE / adaptive composability.
% ED2 provides the detailed mechanistic evidence behind one candidate
% coupling pathway without treating that pathway as a universal mechanism.
%
% Notes:
%   - B/C use locked summary values from the current CMDO analysis.
%   - D loads the real locked external dependence decomposition when the
%     repository is available; otherwise it falls back to current values.
%
% Usage:
%   ED2_IntegrityControls_v2
%
% or:
%   ED2_IntegrityControls_v2([], ...
%       'C:\Users\zyx\CMDO-Reproducibility')
%
% -------------------------------------------------------------------------

close all;

%% ========================================================================
% 0) PATHS
% ========================================================================

thisFile = mfilename('fullpath');

if isempty(thisFile)
    scriptDir = pwd;
else
    scriptDir = fileparts(thisFile);
end

if nargin < 1 || isempty(outputDir)
    outputDir = fullfile(scriptDir,'output');
end

if ~exist(outputDir,'dir')
    mkdir(outputDir);
end

if nargin < 2 || isempty(repoRoot)
    repoRoot = local_find_cmdo_repo(scriptDir);
end

