% 1) STYLE
% ========================================================================

FONT = 'Arial';

FS_LETTER = 22;
FS_TITLE  = 11.5;
FS_AXIS   = 9.2;
FS_TICK   = 8.5;
FS_SMALL  = 8.0;
FS_TINY   = 7.0;

navy   = [0.02 0.27 0.67];
