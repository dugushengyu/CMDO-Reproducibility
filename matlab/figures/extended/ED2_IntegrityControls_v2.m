    u10Path = fullfile( ...
        repoRoot, ...
        'U10_Prospective_ECG', ...
        '02_Posthoc_Diagnostics', ...
        'U10_DEPENDENCE_DECOMPOSITION.csv');

    if isfile(u10Path)

        U10 = readtable( ...
            u10Path, ...
            'VariableNamingRule','preserve');

        need = { ...
            'dataset', ...
            'budget', ...
            'shared_adaptive_gain_pct', ...
            'shared_constant_mean_gain_pct'};

