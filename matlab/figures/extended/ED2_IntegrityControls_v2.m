corr_sep    = 0.056;

disp_shared = 9.45;
disp_sep    = 2.19;

corr_drop = 100*(1-corr_sep/corr_shared);
disp_drop = 100*(1-disp_sep/disp_shared);

% Finite-audit consequences of the strict role-separated control.
cost_vals = [6.54, -85.55, 98.80];

% Locked external mechanism checks.
