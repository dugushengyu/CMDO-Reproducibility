function ed_panel_letter(fig,ax,labelText)
% Place panel letters outside the axes without changing axes geometry.

drawnow;

positionValue = ax.Position;

xValue = max( ...
    0.008, ...
    positionValue(1)-0.030);

yValue = min( ...
    0.970, ...
    positionValue(2)+positionValue(4)+0.006);

annotation( ...
    fig, ...
    'textbox', ...
    [xValue yValue 0.025 0.028], ...
    'String',labelText, ...
    'LineStyle','none', ...
    'FitBoxToText','off', ...
    'FontName','Arial', ...
    'FontSize',15, ...
    'FontWeight','bold', ...
    'HorizontalAlignment','left', ...
    'VerticalAlignment','middle');

end


function q = ed_quantile(values,probability)

values = sort(double(values(:)));
values = values(isfinite(values));

if isempty(values)
    q = NaN;
    return;
end

if numel(values)==1
    q = values;
    return;
end

rankValue = ...
    1 + ...
    (numel(values)-1)*probability;

lowerIndex = floor(rankValue);
upperIndex = ceil(rankValue);

if lowerIndex==upperIndex

    q = values(lowerIndex);

else

    q = ...
        values(lowerIndex) ...
        + ...
        (rankValue-lowerIndex) ...
        * ...
        (values(upperIndex)-values(lowerIndex));
end

end


function colorMapValue = ed_white_to_color(targetColor,nColors)

if nargin < 2
    nColors = 256;
end

targetColor = double(targetColor(:)');

colorMapValue = [ ...
    linspace(1,targetColor(1),nColors)', ...
    linspace(1,targetColor(2),nColors)', ...
    linspace(1,targetColor(3),nColors)'];

end


function shortName = ed_short_u6(targetName)

targetName = string(targetName);

switch targetName

    case "ACS_PUBLIC_COVERAGE_2024_FL"
        shortName = 'ACS-FL';

    case "ACS_PUBLIC_COVERAGE_2024_IL"
        shortName = 'ACS-IL';

    case "ACS_PUBLIC_COVERAGE_2024_OH"
        shortName = 'ACS-OH';

    case "ACS_PUBLIC_COVERAGE_2024_PA"
        shortName = 'ACS-PA';

    case "ACS_PUBLIC_COVERAGE_2024_TX"
        shortName = 'ACS-TX';

    case "DERMA_CLEAN"
        shortName = 'Derma-clean';

    case "DERMA_NOISE_0_08"
        shortName = 'Derma-noise';

    case "DERMA_BLUR_1_0"
        shortName = 'Derma-blur';

    case "DERMA_GAMMA_1_4"
        shortName = 'Derma-gamma';

    case "DERMA_JPEG_35"
        shortName = 'Derma-JPEG';

    case "DERMA_DOWNSAMPLE_14"
        shortName = 'Derma-downsample';

    case "CIFAR_CAT_DOG_CLEAN"
        shortName = 'CIFAR-clean';

    case "CIFAR_CAT_DOG_GRAYSCALE"
        shortName = 'CIFAR-greyscale';

    case "CIFAR_CAT_DOG_NOISE_0_10"
        shortName = 'CIFAR-noise';

    case "CIFAR_CAT_DOG_BLUR_1_2"
        shortName = 'CIFAR-blur';

    case "CIFAR_CAT_DOG_JPEG_30"
        shortName = 'CIFAR-JPEG';

    otherwise
        shortName = char(replace(targetName,"_","-"));
end

end
