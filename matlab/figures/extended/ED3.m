function stageDir = ed_extract(dataDir,cacheDir,zipName)

zipPath = fullfile(dataDir,zipName);

if ~exist(zipPath,'file')
    error( ...
        'ED:MissingZip', ...
        'Missing canonical archive: %s', ...
        zipPath);
end

stageDir = fullfile( ...
    cacheDir, ...
    erase(zipName,'.zip'));

readyFile = fullfile(stageDir,'.ready');

if ~exist(readyFile,'file')

    if exist(stageDir,'dir')
        rmdir(stageDir,'s');
    end

    mkdir(stageDir);
    unzip(zipPath,stageDir);

    fid = fopen(readyFile,'w');

    if fid > 0
        fprintf(fid,'ready\n');
        fclose(fid);
    end
end

end


function T = ed_read(stageDir,fileName)

hits = dir(fullfile(stageDir,'**',fileName));

if isempty(hits)
    error( ...
        'ED:MissingCSV', ...
        'CSV not found after extraction: %s', ...
        fileName);
end

T = readtable( ...
    fullfile(hits(1).folder,hits(1).name), ...
    'VariableNamingRule','preserve');

end


