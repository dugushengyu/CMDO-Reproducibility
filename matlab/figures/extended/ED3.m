function ed_violin(ax,x0,v,faceColor,halfWidth,faceAlpha)

v = double(v(:));
v = v(isfinite(v));

if numel(v) < 2
    return;
end

vMin = min(v);
vMax = max(v);

if vMax <= vMin
    vMin = vMin-1e-6;
    vMax = vMax+1e-6;
end

yGrid = linspace(vMin,vMax,180)';

sigmaValue = std(v,0);

bandwidth = ...
    1.06 * sigmaValue * numel(v)^(-1/5);

if ~isfinite(bandwidth) || bandwidth <= 0
    bandwidth = max((vMax-vMin)/20,eps);
end

z = bsxfun(@minus,yGrid,v') / bandwidth;

density = ...
    mean(exp(-0.5*z.^2),2) / ...
    (bandwidth*sqrt(2*pi));

if max(density) <= 0 || ~all(isfinite(density))
    density = ones(size(density));
end

width = ...
    halfWidth * density / max(density);

patch( ...
    ax, ...
    [x0-width;flipud(x0+width)], ...
    [yGrid;flipud(yGrid)], ...
    faceColor, ...
    'FaceAlpha',faceAlpha, ...
    'EdgeColor',[0.45 0.45 0.45], ...
    'LineWidth',0.6, ...
    'HandleVisibility','off');

end


function tf = ed_to_logical(value)
% Convert table cell/string/numeric/logical values into one logical scalar.

if isempty(value)
    tf = false;
    return;
end

while iscell(value)

    if isempty(value)
        tf = false;
        return;
    end

    value = value{1};
end

if islogical(value)

    tf = any(value(:));

elseif isnumeric(value)

    numericValue = double(value(:));

    tf = any( ...
        isfinite(numericValue) & ...
        numericValue ~= 0);

else

    textValue = lower(strtrim(string(value)));

    trueValues = [ ...
        "true", ...
        "1", ...
        "yes", ...
        "y", ...
        "pass", ...
        "passed", ...
        "eligible"];

    tf = any(ismember(textValue,trueValues));
end

tf = logical(tf);

end


%% ========================================================================
% Draggable panel-b textbox helpers
% ========================================================================
function ed_start_label_drag(labelHandle,figHandle)

if ~isgraphics(labelHandle) || ~isgraphics(figHandle)
    return;
end

set( ...
    figHandle, ...
    'Pointer','fleur', ...
    'WindowButtonMotionFcn', ...
    @(~,~) ed_drag_label(labelHandle), ...
    'WindowButtonUpFcn', ...
    @(~,~) ed_stop_label_drag(figHandle));

end


function ed_drag_label(labelHandle)

if ~isgraphics(labelHandle)
    return;
end

ax = ancestor(labelHandle,'axes');

if isempty(ax) || ~isgraphics(ax)
    return;
end

currentPoint = ax.CurrentPoint;

xValue = currentPoint(1,1);
yValue = currentPoint(1,2);

xLimits = ax.XLim;
yLimits = ax.YLim;

xPadding = 0.025 * diff(xLimits);
yPadding = 0.040 * diff(yLimits);

xValue = min( ...
    max(xValue,xLimits(1)+xPadding), ...
    xLimits(2)-xPadding);

yValue = min( ...
    max(yValue,yLimits(1)+yPadding), ...
    yLimits(2)-yPadding);

labelHandle.Position = [xValue yValue 0];

anchorPoint = getappdata( ...
    labelHandle, ...
    'AnchorPoint');

leaderHandle = getappdata( ...
    labelHandle, ...
    'LeaderHandle');

if isgraphics(leaderHandle)

    leaderHandle.XData = [anchorPoint(1),xValue];
    leaderHandle.YData = [anchorPoint(2),yValue];
end

drawnow limitrate nocallbacks;

end


function ed_stop_label_drag(figHandle)

if ~isgraphics(figHandle)
    return;
end

set( ...
    figHandle, ...
    'Pointer','arrow', ...
    'WindowButtonMotionFcn','', ...
    'WindowButtonUpFcn','');

end
