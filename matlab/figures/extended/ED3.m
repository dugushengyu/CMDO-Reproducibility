    ['  Reference/full rows intentionally excluded from panel b: ' ...
     'DIRECT_FULL, ORACLE_FULL, PLUGIN_FULL\n']);

%% ========================================================================
% Manual label adjustment and final export
% ========================================================================
drawnow;

if usejava('desktop')

    instructionBox = annotation( ...
        fig, ...
        'textbox', ...
        [0.260 0.010 0.455 0.032], ...
        'String', ...
        ['Drag the seven panel-b textboxes, then click ' ...
         '"Save panel b labels & figure"'], ...
        'HorizontalAlignment','center', ...
        'VerticalAlignment','middle', ...
        'FontName','Arial', ...
        'FontSize',9, ...
        'FontWeight','bold', ...
        'BackgroundColor',[1.00 1.00 0.88], ...
        'EdgeColor',[0.65 0.65 0.45], ...
        'FitBoxToText','off');

    finishButton = uicontrol( ...
        fig, ...
        'Style','pushbutton', ...
        'Units','normalized', ...
        'Position',[0.735 0.010 0.205 0.034], ...
        'String','Save panel b labels & figure', ...
        'FontSize',9.2, ...
        'FontWeight','bold', ...
        'Callback',@(~,~) uiresume(fig));

    uiwait(fig);

    if ~isgraphics(fig)
        return;
    end

    labelPosB = nan(numel(labelHandlesB),2);

    for i = 1:numel(labelHandlesB)

        p = labelHandlesB(i).Position;
        labelPosB(i,:) = p(1:2);
    end

    save( ...
        panelBPositionFile, ...
        'labelPosB', ...
        'panelBMethodCodes', ...
        'panelBLabels');

    if isgraphics(finishButton)
        delete(finishButton);
    end

    if isgraphics(instructionBox)
        delete(instructionBox);
    end
end

drawnow;

ed_save( ...
    fig, ...
    outDir, ...
    'ExtendedData3_Pair_Complete_Candidate_Audit');

fprintf( ...
    '\nPanel-b label positions saved to:\n%s\n', ...
    panelBPositionFile);

end


