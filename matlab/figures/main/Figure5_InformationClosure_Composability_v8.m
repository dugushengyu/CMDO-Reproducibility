function repoRoot = local_find_cmdo_repo(scriptDir)

repoRoot = '';

starts = {scriptDir,pwd};

for s = 1:numel(starts)

    p = starts{s};

    for k = 1:8

        if isempty(p)
            break;
        end

        if ...
                isfolder(fullfile(p,'source_data')) && ...
                isfolder(fullfile(p,'U10_Prospective_ECG'))

            repoRoot = p;
            return;

        end

        parent = fileparts(p);

        if strcmp(parent,p)
            break;
        end

        p = parent;

    end

end

userHome = strtrim(getenv('USERPROFILE'));

if isempty(userHome)
    userHome = strtrim(getenv('HOME'));
end

if ~isempty(userHome)

    candidates = { ...
        fullfile(userHome,'CMDO-Reproducibility'), ...
        fullfile(userHome,'Documents','CMDO-Reproducibility'), ...
        fullfile(userHome,'Desktop','CMDO-Reproducibility')};

    for i = 1:numel(candidates)

        p = candidates{i};

        if ...
                isfolder(fullfile(p,'source_data')) && ...
                isfolder(fullfile(p,'U10_Prospective_ECG'))

            repoRoot = p;
            return;

        end

    end

end

