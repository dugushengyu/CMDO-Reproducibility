    0.025,0.955, ...
    red, ...
    FONT, ...
    FS_LETTER, ...
    FS_TITLE);

% Xi is the central PRESERVE coordinate:
% adaptive risk relative to the matched fixed-use comparator.
text( ...
    axA0, ...
    0.770,0.880, ...
    '$\Xi=[R_{\rm adaptive}-R_{\rm fixed}(\bar w)]/V$', ...
    'Interpreter','latex', ...
    'HorizontalAlignment','center', ...
    'VerticalAlignment','middle', ...
    'FontName',FONT, ...
    'FontSize',8.5, ...
    'Color',purple);

local_summary_box( ...
    axA0, ...
    [0.575 0.740 0.390 0.115], ...
    purple, ...
    { ...
     sprintf('\\Xi > 0: %d/4',nXiPositive), ...
     sprintf('benefit \\rightarrow harm: %d/4',benefitToHarmN) ...
    }, ...
    FONT, ...
    7.7);

