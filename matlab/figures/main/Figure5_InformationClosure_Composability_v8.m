function Figure5_InformationClosure_Composability_v8(outputDir, repoRoot)
% FIGURE5_INFORMATIONCLOSURE_COMPOSABILITY_V8
%
% CMDO Figure 5 — PRESERVE
% Adaptive composability and the boundary of adaptive evidence reuse
%
% Final main-text architecture:
%
%   Figure 3 : IDENTIFY
%   Figure 4 : REUSE
%   Figure 5 : PRESERVE
%
% Figure 5 — PRESERVE
%
% Central proposition:
%   Evidence value must survive adaptation.
%
% Panels:
%   A  Adaptation can consume fixed-use value
%   B  Locked testing limits mechanism generality
%   C  Breaking pairing reduces composition cost
%   D  Adaptation is worthwhile only when H > A + C
%
% This script intentionally DOES NOT redraw:
%   - U11 information-closure witness        -> Figure 3
%   - 185-state admissibility synthesis      -> Figure 4
%
% It uses only the U9B adaptive-composition decomposition and the
% separately locked / post-completion U10 analyses needed for PRESERVE.
%
% Usage:
%
%   Figure5_InformationClosure_Composability_v8
%
% or
%
%   Figure5_InformationClosure_Composability_v8([], ...
%       'C:\Users\zyx\CMDO-Reproducibility')
%
% -------------------------------------------------------------------------

close all;

%% ========================================================================
% 0) STYLE
% ========================================================================

FONT = 'Arial';

FS_LETTER = 21;
FS_TITLE  = 11.5;
FS_AXIS   = 10.5;
FS_TICK   = 9.5;
FS_SMALL  = 9.0;
FS_TINY   = 8.0;

blue   = [0.02 0.29 0.70];
navy   = [0.02 0.24 0.63];
green  = [0.02 0.48 0.20];
red    = [0.82 0.05 0.04];
purple = [0.43 0.17 0.70];

grey   = [0.43 0.43 0.43];
lgrey  = [0.82 0.82 0.82];
dgrey  = [0.22 0.22 0.22];

panelRed    = local_mix(red,    [1 1 1],0.79);
panelPurple = local_mix(purple, [1 1 1],0.81);

lightGreen  = local_mix(green,[1 1 1],0.88);
lightRed    = local_mix(red,  [1 1 1],0.90);
lightPurple = local_mix(purple,[1 1 1],0.88);

%% ========================================================================
% 1) PATHS
% ========================================================================

thisFile = mfilename('fullpath');

if isempty(thisFile)
    scriptDir = pwd;
else
    scriptDir = fileparts(thisFile);
end

if nargin < 2 || isempty(repoRoot)
    repoRoot = local_find_cmdo_repo(scriptDir);
end

if isempty(repoRoot)
    error(['Could not locate CMDO-Reproducibility.' newline ...
           'Run with an explicit repository path.']);
end

if nargin < 1 || isempty(outputDir)
    outputDir = fullfile(scriptDir,'output');
end

if ~exist(outputDir,'dir')
    mkdir(outputDir);
end

fprintf('\n============================================================\n');
fprintf(' CMDO FIGURE 5 — PRESERVE\n');
fprintf(' Adaptive composability and adaptation frontier\n');
fprintf('============================================================\n');
fprintf('Repository : %s\n',repoRoot);
fprintf('Output     : %s\n',outputDir);

%% ========================================================================
% 2) U9B — ADAPTIVE-COMPOSITION EXCESS RISK
% ========================================================================

u9bPath = fullfile( ...
    repoRoot, ...
    'source_data', ...
    'figure6_admissibility', ...
    'U9B_external_composability_decomposition.csv');

if ~isfile(u9bPath)
    error('Missing U9B decomposition:\n%s',u9bPath);
end

U9B = readtable(u9bPath);

local_require_vars( ...
    U9B, ...
    {'budget', ...
     'scalar_gain_pct', ...
     'observed_gain_pct', ...
     'xi_downward_pp'}, ...
    'U9B composability decomposition');

u9bBudget = double(U9B.budget);
u9bFixed  = double(U9B.scalar_gain_pct);
u9bAdapt  = double(U9B.observed_gain_pct);
u9bXi     = double(U9B.xi_downward_pp);

% Preserve the original percentage-point decomposition for frozen auditing.
xiResidual = local_nanmax(abs((u9bFixed-u9bAdapt)-u9bXi));

% Convert fixed/adaptive gains into the normalized-risk coordinates used
% by the main-text PRESERVE definition:
%
%   R/V = 1 - gain/100
%   Xi  = [R_adaptive - R_fixed(mean w)]/V
%
% Therefore the original downward displacement in percentage points is
% exactly 100*Xi.
u9bFixedRisk = ...
    1 - u9bFixed./100;

u9bAdaptRisk = ...
    1 - u9bAdapt./100;

u9bXiRisk = ...
    u9bXi./100;

xiRiskResidual = ...
    local_nanmax( ...
    abs( ...
    (u9bAdaptRisk-u9bFixedRisk) - ...
    u9bXiRisk));

assert( ...
    xiResidual < 1e-9, ...
    'U9B Xi decomposition mismatch.');

assert( ...
    xiRiskResidual < 1e-12, ...
    'U9B normalized Xi decomposition mismatch.');

nXiPositive = nnz(u9bXi > 0);

benefitToHarm = ...
    (u9bFixed > 0) & ...
    (u9bAdapt < 0);

benefitToHarmN = nnz(benefitToHarm);

%% ========================================================================
% 3) U10 — POST-COMPLETION DEPENDENCE DECOMPOSITION
% ========================================================================

u10Path = fullfile( ...
    repoRoot, ...
    'U10_Prospective_ECG', ...
    '02_Posthoc_Diagnostics', ...
    'U10_DEPENDENCE_DECOMPOSITION.csv');

if ~isfile(u10Path)
    error('Missing U10 dependence decomposition:\n%s',u10Path);
end

U10 = readtable(u10Path);

local_require_vars( ...
    U10, ...
    {'dataset', ...
     'budget', ...
     'shared_adaptive_gain_pct', ...
     'shared_constant_mean_gain_pct', ...
     'B', ...
     'direct_mse', ...
     'shared_constant_mean_weight', ...
     'shared_adaptive_mse', ...
     'shared_constant_mean_mse', ...
     'shared_permuted_weight_mse', ...
     'shared_permuted_weight_mse_sd', ...
     'shared_tax_weight_heterogeneity'}, ...
    'U10 dependence decomposition');

u10Dataset = string(U10.dataset);
u10Budget  = double(U10.budget);

datasetOrder = ["georgia","cpsc_2018"];

rowOrder = [];

for d = 1:numel(datasetOrder)

    idx = find(u10Dataset == datasetOrder(d));

    [~,o] = sort(u10Budget(idx),'ascend');

    rowOrder = [rowOrder; idx(o)]; %#ok<AGROW>

end

U10 = U10(rowOrder,:);

u10Dataset = string(U10.dataset);
u10Budget  = double(U10.budget);

u10Adaptive = double(U10.shared_adaptive_gain_pct);
u10Fixed    = double(U10.shared_constant_mean_gain_pct);

assert(height(U10)==8, ...
    'Expected eight U10 cohort-budget cells.');

%% ========================================================================
% 4) U10 — HETEROGENEITY / ALLOCATION / COMPOSITION FRONTIER
% ========================================================================

u10B     = double(U10.B);
u10V     = double(U10.direct_mse);
u10MeanW = double(U10.shared_constant_mean_weight);

u10Lambda = (u10B.^2)./u10V;

u10Wstar = 1./(1+u10Lambda);

% matched-mean adaptive composition excess risk
u10XiExact = ...
    (double(U10.shared_adaptive_mse) - ...
     double(U10.shared_constant_mean_mse)) ./ u10V;

% permutation diagnostic
u10XiPerm = ...
    (double(U10.shared_permuted_weight_mse) - ...
     double(U10.shared_constant_mean_mse)) ./ u10V;

u10XiPermSD = ...
    double(U10.shared_permuted_weight_mse_sd) ./ u10V;

% role-separated heterogeneity-only prediction
u10XiHet = ...
    double(U10.shared_tax_weight_heterogeneity) ./ u10V;

% best single fixed reuse weight across states
wGlobal = 1/(1 + local_nanmean(u10Lambda));

% heterogeneity opportunity
u10Hi = ...
    (1+u10Lambda) .* ...
    (u10Wstar-wGlobal).^2;

% allocation error
u10Ai = ...
    (1+u10Lambda) .* ...
    (u10MeanW-u10Wstar).^2;

Hhac = local_nanmean(u10Hi);
Ahac = local_nanmean(u10Ai);

% mean composition excess risk
Chac  = local_nanmean(u10XiExact);
Cperm = local_nanmean(u10XiPerm);
Chet  = local_nanmean(u10XiHet);

% frontier coordinates
xShared = Ahac + Chac;
xPerm   = Ahac + Cperm;
xRole   = Ahac + Chet;

marginShared = Hhac - xShared;
marginPerm   = Hhac - xPerm;
marginRole   = Hhac - xRole;

cReductionPct = ...
    100*(Chac-Cperm)/Chac;

%% ------------------------------------------------------------------------
% Frozen numerical fingerprints
% -------------------------------------------------------------------------

assert(abs(Hhac -0.08614018) < 5e-7, ...
    'U10 H fingerprint mismatch.');

assert(abs(Ahac -0.01403814) < 5e-7, ...
    'U10 A fingerprint mismatch.');

assert(abs(Chac -0.21760208) < 5e-7, ...
    'U10 C fingerprint mismatch.');

assert(abs(Cperm-0.03214915) < 5e-7, ...
    'U10 permutation-C fingerprint mismatch.');

assert(abs(Chet -0.03136104) < 5e-7, ...
    'U10 role-separated-C fingerprint mismatch.');

%% ========================================================================
% 5) FROZEN PROSPECTIVE U10 CHALLENGE
% ========================================================================
%
% These are the locked prospective cohort-level summaries:
%
%                      role separation   cross-fitting
% Georgia                   3/4              3/4
% CPSC 2018                 2/4              2/4
%
% Georgia met the prespecified cohort-level criterion.
% CPSC 2018 did not.
%
% These are NOT reconstructed from the post-completion CSV above.

lockedChecks = [ ...
    3 3; ...
    2 2];

