        'FontName',FONT, ...
        'FontSize',8.0, ...
        'FontWeight','bold', ...
        'Color',purple);

end

yMinA = ...
    local_nanmin( ...
    [u9bFixedRisk(:);u9bAdaptRisk(:);1]);

