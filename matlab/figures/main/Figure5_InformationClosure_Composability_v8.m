yline( ...
    axA,1,'--','Direct = 1', ...
    'Color',[0.38 0.38 0.38], ...
    'LineWidth',0.9, ...
    'LabelHorizontalAlignment','right', ...
    'LabelVerticalAlignment','bottom');

