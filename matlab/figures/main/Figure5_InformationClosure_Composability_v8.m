    repoRoot, ...
    'U10_Prospective_ECG', ...
    '01_Prospective_Result', ...
    'U10_PRIMARY_RESULT.json');

if isfile(u10PrimaryJson)

    J = jsondecode(fileread(u10PrimaryJson));

    if isfield(J,'primary_verdict')

        rawVerdict = string(J.primary_verdict);

        assert( ...
            strcmpi(rawVerdict,"MECHANISM_NOT_CONFIRMED"), ...
            'Unexpected U10 frozen primary verdict.');

    end

end

