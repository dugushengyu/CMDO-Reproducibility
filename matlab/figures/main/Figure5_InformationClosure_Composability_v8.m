    axA, ...
    xA, ...
    u9bFixedRisk, ...
    74, ...
    's', ...
    'filled', ...
    'MarkerFaceColor',green, ...
    'MarkerEdgeColor','w', ...
    'LineWidth',0.7);

% adaptive observer
hAdaptive = scatter( ...
    axA, ...
    xA, ...
    u9bAdaptRisk, ...
    78, ...
    'o', ...
    'filled', ...
    'MarkerFaceColor',red, ...
    'MarkerEdgeColor','w', ...
    'LineWidth',0.7);

% Label the adaptive-composition gap in the native Xi units.
for i = 1:numel(xA)

    text( ...
        axA, ...
        xA(i)+0.10, ...
        0.5*(u9bFixedRisk(i)+u9bAdaptRisk(i)), ...
