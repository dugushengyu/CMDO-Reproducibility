function pValue = f5_spearman_pvalue(rhoValue, sampleCount)
% Two-sided Student-t approximation for Spearman correlation.
% For the canonical U6 data this reproduces p = 1.10059e-06.

if sampleCount <= 2 || ~isfinite(rhoValue)
    pValue = NaN;
    return;
end

rhoValue = max(min(rhoValue, 1 - eps), -1 + eps);

degreesFreedom = sampleCount - 2;

tStatistic = ...
    abs(rhoValue) .* ...
    sqrt(degreesFreedom ./ (1 - rhoValue.^2));

betaArgument = ...
    degreesFreedom ./ ...
    (degreesFreedom + tStatistic.^2);

pValue = betainc( ...
    betaArgument, ...
    degreesFreedom / 2, ...
    0.5);

end


function criticalValue = f5_tcritical95(degreesFreedom)
% Two-sided 95% Student-t critical value without Statistics Toolbox.

if degreesFreedom <= 0
    criticalValue = 1.96;
    return;
end

betaValue = betaincinv( ...
    0.05, ...
    degreesFreedom / 2, ...
    0.5);

criticalValue = sqrt( ...
    degreesFreedom .* ...
    (1 - betaValue) ./ betaValue);

end


function f5_violin(ax, xCenter, values, faceColor, maxHalfWidth)
% Toolbox-independent Gaussian KDE violin.

values = double(values(:));
values = values(isfinite(values));

if numel(values) < 2
    return;
end

valueMinimum = min(values);
valueMaximum = max(values);

if valueMaximum <= valueMinimum
    valueMinimum = valueMinimum - 1e-6;
    valueMaximum = valueMaximum + 1e-6;
end

yGrid = linspace( ...
    valueMinimum, ...
    valueMaximum, ...
    180)';

valueSigma = std(values, 0);

bandwidth = ...
    1.06 .* valueSigma .* numel(values).^(-1/5);

if ~isfinite(bandwidth) || bandwidth <= 0
    bandwidth = max( ...
        (valueMaximum - valueMinimum) / 20, ...
        eps);
end

zValue = ...
    (yGrid - values') ./ bandwidth;

density = ...
    mean(exp(-0.5 .* zValue.^2), 2) ...
    ./ (bandwidth .* sqrt(2*pi));

maximumDensity = max(density);

if ~isfinite(maximumDensity) || maximumDensity <= 0
    return;
end

halfWidth = ...
    maxHalfWidth .* density ./ maximumDensity;

patch( ...
    ax, ...
    [xCenter - halfWidth; ...
     flipud(xCenter + halfWidth)], ...
    [yGrid; flipud(yGrid)], ...
    faceColor, ...
    'FaceAlpha', 0.20, ...
    'EdgeColor', faceColor, ...
    'LineWidth', 0.45, ...
    'HandleVisibility', 'off');

end


