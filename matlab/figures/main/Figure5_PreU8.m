if ~isgraphics(labelHandle) || ~isgraphics(figHandle)
    return;
end

set(figHandle, ...
    'Pointer', 'fleur', ...
    'WindowButtonMotionFcn', ...
    @(~, ~) f5_drag_label(labelHandle), ...
    'WindowButtonUpFcn', ...
    @(~, ~) f5_stop_label_drag(figHandle));

end


function f5_drag_label(labelHandle)
% Move one label and update its leader line.

if ~isgraphics(labelHandle)
    return;
end

ax = ancestor(labelHandle, 'axes');

if isempty(ax) || ~isgraphics(ax)
    return;
end

currentPoint = ax.CurrentPoint;

xValue = currentPoint(1,1);
yValue = currentPoint(1,2);

xLimits = ax.XLim;
yLimits = ax.YLim;

xPadding = 0.025 .* diff(xLimits);
yPadding = 0.040 .* diff(yLimits);

xValue = min( ...
    max(xValue, xLimits(1) + xPadding), ...
    xLimits(2) - xPadding);

yValue = min( ...
    max(yValue, yLimits(1) + yPadding), ...
    yLimits(2) - yPadding);

labelHandle.Position = [xValue, yValue, 0];

anchorPoint = getappdata( ...
    labelHandle, ...
    'AnchorPoint');

leaderHandle = getappdata( ...
    labelHandle, ...
    'LeaderHandle');

if isgraphics(leaderHandle)

    leaderHandle.XData = [anchorPoint(1), xValue];
    leaderHandle.YData = [anchorPoint(2), yValue];
end

drawnow limitrate nocallbacks;

end


function f5_stop_label_drag(figHandle)
% Finish dragging.

if ~isgraphics(figHandle)
    return;
end

set(figHandle, ...
    'Pointer', 'arrow', ...
    'WindowButtonMotionFcn', '', ...
    'WindowButtonUpFcn', '');

end
