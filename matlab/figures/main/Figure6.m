function v = getvar(tbl, candidates)
    names = ...
        tbl.Properties.VariableNames;
    names_lower = ...
        lower(string(names));
    candidates_lower = ...
        lower(string(candidates));
    idx = find( ...
        ismember( ...
            names_lower, ...
            candidates_lower), ...
        1, ...
        'first');
    if isempty(idx)
        error( ...
            'Could not find any of these variables:\n  %s', ...
            strjoin(string(candidates),', '));
    end
    v = ...
        tbl.(names{idx});
end
