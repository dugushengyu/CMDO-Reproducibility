function auc = local_auc_rank(score,y)

score = double(score(:));
y = double(y(:));

m = isfinite(score) & isfinite(y);

score = score(m);
y = y(m);

n1 = nnz(y==1);
n0 = nnz(y==0);

if n1==0 || n0==0

    auc = NaN;
    return;

end

r = local_tied_rank(score);

sumR1 = sum(r(y==1));

auc = ...
    (sumR1 - n1*(n1+1)/2) / ...
    (n1*n0);

end

function r = local_tied_rank(v)

v = double(v(:));

n = numel(v);

[sv,ord] = sort(v,'ascend');

r = zeros(n,1);

i = 1;

while i<=n

    j = i;

    while j<n && sv(j+1)==sv(i)
        j = j+1;
    end

    r(ord(i:j)) = 0.5*(i+j);

    i = j+1;

end

end

function local_require_vars(T,vars,sourceName)

missing = strings(0,1);

for i = 1:numel(vars)

    if ~ismember(vars{i},T.Properties.VariableNames)

        missing(end+1,1) = string(vars{i}); %#ok<AGROW>

    end

end

if ~isempty(missing)

    error( ...
        '%s missing variables: %s', ...
        sourceName, ...
        strjoin(cellstr(missing),', '));

end

end

