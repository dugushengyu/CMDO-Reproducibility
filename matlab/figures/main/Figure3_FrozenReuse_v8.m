function U11 = local_load_u11(repoRoot)

paths.gp = fullfile( ...
    repoRoot, ...
    'U11_Information_Closure', ...
    '01_Result', ...
    'U11_WORLD_PLUS_georgia_v0.1.csv');

paths.gm = fullfile( ...
    repoRoot, ...
    'U11_Information_Closure', ...
    '01_Result', ...
    'U11_WORLD_MINUS_georgia_v0.1.csv');

paths.cp = fullfile( ...
    repoRoot, ...
    'U11_Information_Closure', ...
    '01_Result', ...
    'U11_WORLD_PLUS_cpsc_2018_v0.1.csv');

paths.cm = fullfile( ...
    repoRoot, ...
    'U11_Information_Closure', ...
    '01_Result', ...
    'U11_WORLD_MINUS_cpsc_2018_v0.1.csv');

f = fieldnames(paths);

for i = 1:numel(f)

    if ~isfile(paths.(f{i}))
        error( ...
            'Missing U11 world file:\n%s', ...
            paths.(f{i}));
    end

end

Tgp = readtable(paths.gp);
Tgm = readtable(paths.gm);

Tcp = readtable(paths.cp);
Tcm = readtable(paths.cm);

U11.georgia = local_parse_u11_pair( ...
    Tgp,Tgm,'Georgia');

U11.cpsc = local_parse_u11_pair( ...
    Tcp,Tcm,'CPSC 2018');

end

function S = local_parse_u11_pair(Tp,Tm,nameStr)

local_require_vars( ...
    Tp, ...
    {'score_af','predicted_af','synthetic_outcome'}, ...
    [nameStr ' WORLD+']);

local_require_vars( ...
    Tm, ...
    {'score_af','predicted_af','synthetic_outcome'}, ...
    [nameStr ' WORLD-']);

sp = double(Tp.score_af(:));
sm = double(Tm.score_af(:));

pp = double(Tp.predicted_af(:));
pm = double(Tm.predicted_af(:));

ypRaw = double(Tp.synthetic_outcome(:));
ymRaw = double(Tm.synthetic_outcome(:));

assert( ...
    numel(sp)==numel(sm), ...
    'U11 paired worlds have different lengths.');

% If record IDs are available, verify that those channels also match.
if ismember('record_id',Tp.Properties.VariableNames) && ...
        ismember('record_id',Tm.Properties.VariableNames)

    ridP = string(Tp.record_id);
    ridM = string(Tm.record_id);

    assert( ...
        isequal(ridP,ridM), ...
        'U11 record_id channels differ.');

end

scoreResidual = max(abs(sp-sm),[],'omitnan');

predictionIdentity = isequal(pp,pm);

% Preserve original frozen ordering for the monitoring-stream panel.
S.scoreRaw = sp;

% Sort only for the compatible-world visualization.
[scoreSorted,ord] = sort(sp,'ascend');

yp = ypRaw(ord);
ym = ymRaw(ord);

S.name = nameStr;

S.n = numel(sp);

S.score = scoreSorted;

S.yPlus = yp;
S.yMinus = ym;

S.prevalencePlus = mean(ypRaw,'omitnan');
S.prevalenceMinus = mean(ymRaw,'omitnan');

S.aucPlus = local_auc_rank(sp,ypRaw);
S.aucMinus = local_auc_rank(sm,ymRaw);

S.aucGap = abs( ...
    S.aucPlus - S.aucMinus);

S.scoreResidual = scoreResidual;

S.predictionIdentity = predictionIdentity;

end

function local_score_stream(ax,score,color,FONT,FS_AXIS)

score = double(score(:));

score = score(isfinite(score));

Nshow = min(240,numel(score));

idx = unique( ...
    round( ...
    linspace(1,numel(score),Nshow)));

s = score(idx);

x = 1:numel(s);

hold(ax,'on');

% Light vertical score stems.
h = stem( ...
    ax, ...
    x, ...
    s, ...
    'Marker','none', ...
    'Color',color, ...
    'LineWidth',0.55);

try
    h.BaseLine.Visible = 'off';
catch
end

scatter( ...
    ax, ...
    x, ...
    s, ...
    10, ...
    'o', ...
    'filled', ...
    'MarkerFaceColor',color, ...
    'MarkerEdgeColor','w', ...
    'LineWidth',0.25);

xlim(ax,[1 numel(x)]);

scoreMin = min(s,[],'omitnan');
scoreMax = max(s,[],'omitnan');

lo = min(0,scoreMin);
hi = max(1,scoreMax);

span = hi-lo;

if span<=0 || ~isfinite(span)
    span = 1;
end

ylim(ax,[lo-0.03*span hi+0.04*span]);

set( ...
    ax, ...
    'XTick',[1 round(numel(x)/2) numel(x)], ...
    'XTickLabel',{'1','n/2','n'}, ...
    'FontName',FONT, ...
    'FontSize',FS_AXIS, ...
    'TickDir','out', ...
    'LineWidth',0.75, ...
    'Box','off');

xlabel( ...
    ax, ...
    'Record order', ...
    'FontName',FONT, ...
    'FontSize',FS_AXIS);

end

