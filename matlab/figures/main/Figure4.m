function f4_draw_pair_matrix(ax, x0, y0, width, height, pairComplete)
% Draw a coloured 2-by-2 pair-coverage matrix.

cellWidth = width / 2;
cellHeight = height / 2;

labels = { ...
    'P_A \times N_A', ...
    'P_A \times N_B', ...
    'P_B \times N_A', ...
    'P_B \times N_B'};

for q = 1:4
    col = mod(q - 1, 2);
    row = floor((q - 1) / 2);

    kept = pairComplete || q == 1 || q == 4;

    if kept
        faceColor = [0.88 0.96 0.90];
        statusText = 'kept';
    else
        faceColor = [1.00 0.90 0.90];
        statusText = 'discarded';
    end

    x = x0 + col * cellWidth;
    y = y0 + (1 - row) * cellHeight;

    rectangle( ...
        ax, ...
        'Position', [x y cellWidth cellHeight], ...
        'FaceColor', faceColor, ...
        'EdgeColor', [0.35 0.35 0.35], ...
        'LineWidth', 0.8);

    text( ...
        ax, ...
        x + 0.5 * cellWidth, ...
        y + 0.62 * cellHeight, ...
        labels{q}, ...
        'Interpreter', 'tex', ...
        'HorizontalAlignment', 'center', ...
        'VerticalAlignment', 'middle', ...
        'FontSize', 9.5);

    text( ...
        ax, ...
        x + 0.5 * cellWidth, ...
        y + 0.30 * cellHeight, ...
        statusText, ...
        'HorizontalAlignment', 'center', ...
        'VerticalAlignment', 'middle', ...
        'FontSize', 8.5, ...
        'FontWeight', 'bold');
end

end


function f4_violin(ax, xCenter, values, faceColor, maxHalfWidth)
% Draw a toolbox-independent Gaussian KDE violin.

values = double(values(:));
values = values(isfinite(values));

if numel(values) < 2
    return;
end

vMin = min(values);
vMax = max(values);

if vMax <= vMin
    vMin = vMin - 1e-6;
    vMax = vMax + 1e-6;
end

yGrid = linspace(vMin, vMax, 180)';

sigmaV = std(values, 0);

bandwidth = ...
    1.06 * sigmaV * numel(values)^(-1/5);

if ~isfinite(bandwidth) || bandwidth <= 0
    bandwidth = max((vMax - vMin) / 20, eps);
end

z = ...
    (yGrid - values') ...
    ./ bandwidth;

density = ...
    mean(exp(-0.5 * z.^2), 2) ...
    ./ (bandwidth * sqrt(2*pi));

maxDensity = max(density);

if ~isfinite(maxDensity) || maxDensity <= 0
    return;
end

halfWidth = ...
    maxHalfWidth ...
    * density ...
    / maxDensity;

patch( ...
    ax, ...
    [xCenter - halfWidth; ...
     flipud(xCenter + halfWidth)], ...
    [yGrid; flipud(yGrid)], ...
    faceColor, ...
    'FaceAlpha', 0.26, ...
    'EdgeColor', 'none', ...
    'HandleVisibility', 'off');

end


function f4_start_label_drag(labelHandle, figHandle)
% Start dragging one panel-d label.

if ~isgraphics(labelHandle) || ~isgraphics(figHandle)
    return;
end

set(figHandle, ...
    'Pointer', 'fleur', ...
    'WindowButtonMotionFcn', ...
    @(~, ~) f4_drag_label(labelHandle), ...
    'WindowButtonUpFcn', ...
    @(~, ~) f4_stop_label_drag(figHandle));

end


function f4_drag_label(labelHandle)
% Move one label and update its leader line.

if ~isgraphics(labelHandle)
    return;
end

ax = ancestor(labelHandle, 'axes');

if isempty(ax) || ~isgraphics(ax)
    return;
end

point = ax.CurrentPoint;

x = point(1, 1);
y = point(1, 2);

xLimits = ax.XLim;
yLimits = ax.YLim;

xPad = 0.025 * diff(xLimits);
yPad = 0.040 * diff(yLimits);

x = min( ...
    max(x, xLimits(1) + xPad), ...
    xLimits(2) - xPad);

y = min( ...
    max(y, yLimits(1) + yPad), ...
    yLimits(2) - yPad);

labelHandle.Position = [x y 0];

anchor = getappdata(labelHandle, 'AnchorPoint');
leader = getappdata(labelHandle, 'LeaderHandle');

if isgraphics(leader)
    leader.XData = [anchor(1), x];
    leader.YData = [anchor(2), y];
end

drawnow limitrate nocallbacks;

end


function f4_stop_label_drag(figHandle)
% Finish dragging.

if ~isgraphics(figHandle)
    return;
end

set(figHandle, ...
    'Pointer', 'arrow', ...
    'WindowButtonMotionFcn', '', ...
    'WindowButtonUpFcn', '');

end
