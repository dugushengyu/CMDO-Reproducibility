    0.25, 0.27, ...
    {'Cross-fold pairs are discarded', ...
     '\Rightarrow positive certification tax'}, ...
    'Interpreter', 'tex', ...
    'HorizontalAlignment', 'center', ...
    'VerticalAlignment', 'top', ...
    'FontSize', 9.5);

