    'Position', [ ...
        posB(1) + 0.12 * posB(3), ...
        posB(2) + 0.59 * posB(4), ...
        0.34 * posB(3), ...
        0.21 * posB(4)], ...
    'Color', 'w', ...
    'Box', 'on');

hold(axBInset, 'on');

plot(axBInset, [0 0], [-0.35 1.35], '--', ...
    'Color', [0.45 0.45 0.45], ...
    'LineWidth', 0.8);

