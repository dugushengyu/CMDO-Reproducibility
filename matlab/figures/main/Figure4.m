    0.60, 0.045, ...
    sprintf('max|r| = %.2e', maxResidual), ...
    'Units', 'normalized', ...
    'HorizontalAlignment', 'left', ...
    'VerticalAlignment', 'bottom', ...
    'FontWeight', 'bold', ...
    'FontSize', 8.2, ...
    'BackgroundColor', 'w', ...
    'Margin', 1);

