function rho = f4f_spearman(x,y)

x = double(x(:));
y = double(y(:));


m = isfinite(x) & isfinite(y);

x = x(m);
y = y(m);


rx = f4f_tied_rank(x);
ry = f4f_tied_rank(y);


rx = rx-mean(rx);
ry = ry-mean(ry);


den = sqrt(sum(rx.^2).*sum(ry.^2));


if den<=0

    rho = NaN;

else

    rho = sum(rx.*ry)./den;

end

end


function p = f4f_spearman_pvalue(rho,n)

if n<=2 || ~isfinite(rho)

    p = NaN;
    return;

end


rho = max(min(rho,1-eps),-1+eps);

df = n-2;


t = abs(rho).*sqrt( ...
    df./(1-rho.^2));


z = df./(df+t.^2);


p = betainc( ...
    z, ...
    df/2, ...
    0.5);

end


function r = f4f_tied_rank(v)

v = double(v(:));

n = numel(v);


[sv,ord] = sort(v,'ascend');


r = zeros(n,1);


i = 1;


while i<=n

    j = i;

    while j<n && sv(j+1)==sv(i)
        j = j+1;
    end


    r(ord(i:j)) = 0.5*(i+j);

    i = j+1;

end

end


function f4f_fit_band(ax,x,y)

x = double(x(:));
y = double(y(:));


m = isfinite(x) & isfinite(y);

x = x(m);
y = y(m);


n = numel(x);


if n<3
    return;
end


X = [ones(n,1),x];

beta = X\y;


xg = linspace(min(x),max(x),220)';

yg = beta(1)+beta(2).*xg;


res = y-X*beta;


df = max(n-2,1);


s2 = sum(res.^2)./df;


xm = mean(x);

sxx = sum((x-xm).^2);


if ~isfinite(sxx) || sxx<=0
    sxx = eps;
end


se = sqrt( ...
    s2 .* ...
    (1/n+(xg-xm).^2./sxx));


tc = f4f_tcritical95(df);


lo = yg-tc.*se;

hi = yg+tc.*se;


fill( ...
    ax, ...
    [xg;flipud(xg)], ...
    [lo;flipud(hi)], ...
    [0.72 0.72 0.72], ...
    'FaceAlpha',0.22, ...
    'EdgeColor','none', ...
    'HandleVisibility','off');


plot( ...
    ax, ...
    xg, ...
    yg, ...
    'k-', ...
    'LineWidth',1.35, ...
    'HandleVisibility','off');

end


function tcrit = f4f_tcritical95(df)

if df<=0

    tcrit = 1.96;
    return;

end


b = betaincinv( ...
    0.05, ...
    df/2, ...
    0.5);


tcrit = sqrt( ...
    df.*(1-b)./b);

end


function f4f_violin(ax,x0,v,faceColor,halfWidth)

v = double(v(:));

v = v(isfinite(v));


if numel(v)<2
    return;
end


vmin = min(v);
vmax = max(v);


if vmax<=vmin

    vmin = vmin-1e-6;
    vmax = vmax+1e-6;

end


gridY = linspace(vmin,vmax,180)';


sigma = std(v,0);


bw = ...
    1.06 ...
    * sigma ...
    * numel(v)^(-1/5);


if ~isfinite(bw) || bw<=0

    bw = max( ...
        (vmax-vmin)/20, ...
        eps);

end


z = ...
    (gridY-v') ...
    ./ bw;


density = ...
    mean(exp(-0.5*z.^2),2) ...
    ./ (bw*sqrt(2*pi));


m = max(density);


if ~isfinite(m) || m<=0
    return;
end


w = halfWidth*density./m;


patch( ...
    ax, ...
    [x0-w;flipud(x0+w)], ...
    [gridY;flipud(gridY)], ...
    faceColor, ...
    'FaceAlpha',0.24, ...
    'EdgeColor',faceColor*0.82, ...
    'LineWidth',0.50, ...
    'HandleVisibility','off');

end


