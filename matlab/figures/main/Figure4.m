    D.u6_rep.direct_full_auc, ...
    D.u6_rep.direct_full_auc, ...
    18, ...
    'o', ...
    'filled', ...
    'MarkerFaceColor', [0.0000 0.4470 0.7410], ...
    'MarkerEdgeColor', 'none', ...
    'MarkerFaceAlpha', 0.18, ...
    'MarkerEdgeAlpha', 0.18, ...
    'HandleVisibility', 'off');

scatter(axB, ...
    u7AUC.direct, ...
    u7AUC.direct, ...
    20, ...
    '^', ...
    'filled', ...
    'MarkerFaceColor', [0.8500 0.3250 0.0980], ...
    'MarkerEdgeColor', 'none', ...
    'MarkerFaceAlpha', 0.18, ...
    'MarkerEdgeAlpha', 0.18, ...
    'HandleVisibility', 'off');

