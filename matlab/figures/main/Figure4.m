if ~isempty(scriptDir)
    addpath(genpath(scriptDir));
end

cfg = cmdo_config('Figure4');
D = cmdo_load_all(cfg);
rng(20260728, 'twister');

outDir = cfg.outputDir;
if ~exist(outDir, 'dir')
    mkdir(outDir);
end

%% Figure canvas
fig = figure( ...
    'Position', [25 25 1100 900], ...
    'Color', 'w', ...
    'Renderer', 'painters', ...
    'Name', 'CMDO Figure 4', ...
    'NumberTitle', 'off');

tl = tiledlayout( ...
    fig, ...
    2, 2, ...
    'TileSpacing', 'loose', ...
    'Padding', 'loose');

