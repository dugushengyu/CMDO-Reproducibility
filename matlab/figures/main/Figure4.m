    0.755, 0.17, ...
    {'Observation-disjoint sensing:', ...
     'AA \leftrightarrow BB,  AB \leftrightarrow BA', ...
     'All four pair blocks are retained.'}, ...
    'Interpreter', 'tex', ...
    'HorizontalAlignment', 'center', ...
    'VerticalAlignment', 'top', ...
    'FontSize', 8.5);

%% ========================================================================
% b — exact fallback identity with residual-audit inset
% ========================================================================
hold(axB, 'on');
cmdo_safe_panel_letter(axB, 'b');

title(axB, ...
    'Exact fallback identity', ...
    'FontWeight', 'bold', ...
    'FontSize', 11.5);

u7AUC = D.u7_rep(string(D.u7_rep.metric) == "AUC", :);

% Main plot data: slightly larger and less transparent
