function Figure4
%FIGURE4 Full-information pair-complete observer figure.
%
% Restores the canonical Figure 4 content:
%   a  Pair-coverage construction diagram
%   b  Exact fallback identity + residual-audit inset
%   c  Six complete regret distributions with violin envelopes
%   d  Seven-stage efficiency-safety trajectory
%
