title(tl, ...
    'Pair-complete observer validation', ...
    'FontWeight', 'bold', ...
    'FontSize', 17);

% Create all four main axes before the inset so tiledlayout positions settle.
axA = nexttile(tl, 1);
axB = nexttile(tl, 2);
