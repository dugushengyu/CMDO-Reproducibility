axD = nexttile(tl, 4);

%% ========================================================================
% a — pair coverage diagram
% ========================================================================
hold(axA, 'on');
axis(axA, [0 1 0 1]);
axis(axA, 'off');
cmdo_safe_panel_letter(axA, 'a');

title(axA, ...
    'Pair coverage', ...
    'FontWeight', 'bold', ...
    'FontSize', 12);

text(axA, ...
    0.25, 0.88, ...
    'Naive split', ...
    'HorizontalAlignment', 'center', ...
    'FontWeight', 'bold', ...
    'FontSize', 10.5);

text(axA, ...
    0.75, 0.88, ...
    'Pair-complete construction', ...
    'HorizontalAlignment', 'center', ...
    'FontWeight', 'bold', ...
    'FontSize', 10.5);

% Two 2-by-2 pair matrices.
f4_draw_pair_matrix(axA, 0.06, 0.43, 0.37, 0.34, false);
f4_draw_pair_matrix(axA, 0.57, 0.43, 0.37, 0.34, true);

% Naive split consequence.
