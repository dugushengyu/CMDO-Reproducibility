        faceColor = [1.00 0.90 0.90];
        statusText = 'discarded';

    end


    x = x0 + col*cellWidth;


    y = ...
        y0 ...
        + (1-row)*cellHeight;


    rectangle( ...
        ax, ...
        'Position',[ ...
        x y cellWidth cellHeight], ...
        'FaceColor',faceColor, ...
        'EdgeColor',[0.35 0.35 0.35], ...
        'LineWidth',0.7);


    text( ...
