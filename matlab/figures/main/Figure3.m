function f3_drag_label(labelHandle)
% Move a label and update its leader line

if ~isgraphics(labelHandle)
    return;
end

ax = ancestor(labelHandle, 'axes');

if isempty(ax) || ~isgraphics(ax)
    return;
end

cp = ax.CurrentPoint;

x = cp(1, 1);
y = cp(1, 2);

xl = ax.XLim;
yl = ax.YLim;

xPad = 0.02 * (xl(2) - xl(1));
yPad = 0.035 * (yl(2) - yl(1));

x = min( ...
    max(x, xl(1) + xPad), ...
    xl(2) - xPad);

y = min( ...
    max(y, yl(1) + yPad), ...
    yl(2) - yPad);

labelHandle.Position = [x y 0];

anchor = getappdata( ...
    labelHandle, ...
    'AnchorPoint');

leader = getappdata( ...
    labelHandle, ...
    'LeaderHandle');

if isgraphics(leader)
    leader.XData = [anchor(1), x];
    leader.YData = [anchor(2), y];
end

drawnow limitrate nocallbacks;

end


function f3_stop_label_drag(figHandle)
% Finish dragging

if ~isgraphics(figHandle)
    return;
end

set(figHandle, ...
    'Pointer', 'arrow', ...
    'WindowButtonMotionFcn', '', ...
    'WindowButtonUpFcn', '');

end
