    'P_A \times N_A', ...
    'P_A \times N_B', ...
    'P_B \times N_A', ...
    'P_B \times N_B'};


for q = 1:4

    col = mod(q-1,2);
    row = floor((q-1)/2);


    kept = ...
        pairComplete ...
        || q==1 ...
        || q==4;


    if kept

        faceColor = [0.88 0.96 0.90];
        statusText = 'kept';

