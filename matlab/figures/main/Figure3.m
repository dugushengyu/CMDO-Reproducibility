end

end


function f3_violin( ...
    ax,xCenter,values,faceColor,maxHalfWidth)


values = double(values(:));
values = values(isfinite(values));


if numel(values) < 2
    return;
end


vMin = min(values);
vMax = max(values);


if vMax <= vMin

    vMin = vMin-1e-6;
    vMax = vMax+1e-6;

end


yGrid = linspace(vMin,vMax,180)';


sigmaV = std(values,0);


bandwidth = ...
    1.06 ...
    * sigmaV ...
    * numel(values)^(-1/5);


if ~isfinite(bandwidth) || bandwidth <= 0

    bandwidth = ...
        max( ...
        (vMax-vMin)/20, ...
        eps);

end


z = ...
    (yGrid-values') ...
    ./ bandwidth;


density = ...
    mean(exp(-0.5*z.^2),2) ...
    ./ (bandwidth*sqrt(2*pi));


maxDensity = max(density);


if ~isfinite(maxDensity) || maxDensity <= 0
    return;
end


halfWidth = ...
    maxHalfWidth ...
    * density ...
    / maxDensity;


patch( ...
    ax, ...
    [ ...
    xCenter-halfWidth; ...
    flipud(xCenter+halfWidth)], ...
    [ ...
    yGrid; ...
    flipud(yGrid)], ...
    faceColor, ...
    'FaceAlpha',0.26, ...
    'EdgeColor','none', ...
    'HandleVisibility','off');

end
