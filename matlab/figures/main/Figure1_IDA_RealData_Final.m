%  ========================================================================

function draw_real_table_snippet( ...
    ax, ...
    T, ...
    p, ...
    S)


round_box( ...
    ax, ...
    p, ...
    [0.997 0.998 1.000], ...
    [0.55 0.58 0.63], ...
    0.8);


M = ...
    double(T.preview);


names = ...
    string(T.varNames);


nr = ...
    min(3,size(M,1));


nc = ...
    min(4,size(M,2));


M = ...
    M(1:nr,1:nc);


names = ...
    names(1:nc);


x0 = ...
    p(1)+0.014;


y0 = ...
    p(2)+0.025;


W = ...
    p(3)-0.028;


H = ...
    p(4)-0.050;


rowH = ...
    H/(nr+1);


colW = ...
    W/nc;


% -------------------------------------------------------------------------
% Header background
% -------------------------------------------------------------------------
rectangle( ...
    ax, ...
    'Position', ...
    [ ...
    x0 ...
    y0+nr*rowH ...
    W ...
    rowH], ...
    'FaceColor',[0.92 0.95 0.98], ...
    'EdgeColor','none');


% -------------------------------------------------------------------------
% Horizontal grid
% -------------------------------------------------------------------------
for rr = 0:(nr+1)


    yy = ...
        y0 + rr*rowH;


    plot( ...
        ax, ...
        [x0 x0+W], ...
        [yy yy], ...
        '-', ...
        'Color',[0.68 0.70 0.74], ...
        'LineWidth',0.55);


end


% -------------------------------------------------------------------------
% Vertical grid
% -------------------------------------------------------------------------
for cc = 0:nc


    xx = ...
        x0 + cc*colW;


    plot( ...
        ax, ...
        [xx xx], ...
        [y0 y0+H], ...
        '-', ...
        'Color',[0.68 0.70 0.74], ...
        'LineWidth',0.55);


end


% -------------------------------------------------------------------------
% Column names
% -------------------------------------------------------------------------
for c = 1:nc


    nm = ...
        short_name( ...
        names(c), ...
        5);


    text( ...
        ax, ...
        x0+(c-0.5)*colW, ...
        y0+(nr+0.5)*rowH, ...
        char(nm), ...
        'HorizontalAlignment','center', ...
        'VerticalAlignment','middle', ...
        'FontName',S.font, ...
        'FontSize',F(S,5.2), ...
        'FontWeight','bold', ...
        'Color',S.text);


end


% -------------------------------------------------------------------------
% Table values
% -------------------------------------------------------------------------
for r0 = 1:nr


    for c = 1:nc


        text( ...
            ax, ...
            x0+(c-0.5)*colW, ...
            y0+(nr-r0+0.5)*rowH, ...
            sprintf( ...
            '%.2f', ...
            M(r0,c)), ...
            'HorizontalAlignment','center', ...
            'VerticalAlignment','middle', ...
            'FontName',S.font, ...
            'FontSize',F(S,5.0), ...
            'Color',S.text);


    end


end


% -------------------------------------------------------------------------
% Table title — outside / above box
% -------------------------------------------------------------------------
text( ...
    ax, ...
    p(1)+p(3)/2, ...
    p(2)+p(4)+0.025, ...
    'Tabular input', ...
    'HorizontalAlignment','center', ...
    'VerticalAlignment','bottom', ...
    'FontName',S.font, ...
    'FontSize',F(S,6.2), ...
    'FontWeight','bold', ...
    'Color',S.text);


end


function s = short_name( ...
    x, ...
    maxLen)


s = ...
    char(string(x));


s = ...
    strrep( ...
    s, ...
    '_', ...
    '');


if numel(s) > maxLen

    s = ...
        s(1:maxLen);

end


s = ...
    string(s);


end


