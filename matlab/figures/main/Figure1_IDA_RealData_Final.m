function [fpr,tpr] = local_roc( ...
    y, ...
    s)


y = ...
    double(y(:));


s = ...
    double(s(:));


valid = ...
    isfinite(y) & ...
    isfinite(s);


y = ...
    y(valid);


s = ...
    s(valid);


[ss,ord] = ...
    sort( ...
    s, ...
    'descend');


yy = ...
    y(ord);


P = ...
    sum(yy==1);


N = ...
    sum(yy==0);


assert( ...
    P>0 && N>0, ...
    'ROC requires both outcome classes.');


tp = ...
    cumsum(yy==1);


fp = ...
    cumsum(yy==0);


change = [ ...
    find(diff(ss)~=0); ...
    numel(ss)];


tpr = [ ...
    0; ...
    tp(change)/P; ...
    1];


fpr = [ ...
    0; ...
    fp(change)/N; ...
    1];


end


