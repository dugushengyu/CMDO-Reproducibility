hold(axScore,'on');

edges = linspace(0,1,7);
histogram(axScore,scoreDemo,edges, ...
    'FaceColor',local_mix(blue,[1 1 1],0.70), ...
    'EdgeColor',navy,'LineWidth',0.8);

xlim(axScore,[0 1]);
ylim(axScore,[0 5]);

set(axScore,'XTick',[0 0.5 1],'YTick',[], ...
    'Box','off','FontName',FONT,'FontSize',FS_TINY, ...
    'TickDir','out','LineWidth',0.65);

xlabel(axScore,'Score','FontName',FONT,'FontSize',FS_TINY);

text(axB0,0.147,0.830,'Shared scores', ...
    'HorizontalAlignment','center', ...
    'FontName',FONT,'FontSize',FS_TINY,'Color',dgrey);

% Arrow to worlds
local_arrow(axB0,0.255,0.745,0.365,0.745,grey,0.9);

% Two compatible worlds with same scores
scoresW  = linspace(0.08,0.92,12);
ySuccess = [zeros(1,6) ones(1,6)];
yFailure = 1 - ySuccess;

axWorld1 = axes('Parent',pB,'Units','normalized', ...
    'Position',[0.435 0.725 0.175 0.083]);
hold(axWorld1,'on');

scatter(axWorld1,scoresW(ySuccess==0),zeros(1,sum(ySuccess==0)), ...
    14,green,'filled');
scatter(axWorld1,scoresW(ySuccess==1),ones(1,sum(ySuccess==1)), ...
    14,green,'filled');

xlim(axWorld1,[0 1]);
ylim(axWorld1,[-0.18 1.18]);

set(axWorld1,'XTick',[],'YTick',[0 1], ...
    'YTickLabel',{'0','1'}, ...
    'Box','off','FontName',FONT,'FontSize',FS_TINY, ...
    'TickDir','out','LineWidth',0.6);

axWorld2 = axes('Parent',pB,'Units','normalized', ...
    'Position',[0.435 0.615 0.175 0.083]);
hold(axWorld2,'on');

scatter(axWorld2,scoresW(yFailure==0),zeros(1,sum(yFailure==0)), ...
    14,red,'filled');
scatter(axWorld2,scoresW(yFailure==1),ones(1,sum(yFailure==1)), ...
    14,red,'filled');

xlim(axWorld2,[0 1]);
ylim(axWorld2,[-0.18 1.18]);

set(axWorld2,'XTick',[0 0.5 1],'YTick',[0 1], ...
    'YTickLabel',{'0','1'}, ...
    'Box','off','FontName',FONT,'FontSize',FS_TINY, ...
    'TickDir','out','LineWidth',0.6);

text(axB0,0.400,0.777,'WORLD+', ...
    'HorizontalAlignment','right', ...
    'FontName',FONT,'FontSize',FS_TINY, ...
    'FontWeight','bold','Color',green);

text(axB0,0.400,0.678,'WORLD-', ...
    'HorizontalAlignment','right', ...
    'FontName',FONT,'FontSize',FS_TINY, ...
    'FontWeight','bold','Color',red);

text(axB0,0.615,0.770,'AUC 1.00', ...
    'HorizontalAlignment','left', ...
    'FontName',FONT,'FontSize',FS_TINY, ...
    'FontWeight','bold','Color',green);

