function Figure2_IDA_v4(outputDir)
% FIGURE2_IDA_V3
% CMDO Figure 2 — ordered system mechanism / theory figure.
%
% Final intended role:
%   A) The evidential order of deployment evaluation
%   B) IDENTIFY: structural ambiguity -> finite-sample uncertainty
%   C) REUSE: mismatch-versus-uncertainty geometry
%   D) PRESERVE: adaptive excess risk and cross-state adaptation frontier
%
% Visual style is intentionally matched to the final Figure 1:
%   - no poster-style overall title inside the artwork
%   - plain colored panel letters A/B/C/D (NO filled square backgrounds)
%   - blue = observability / IDENTIFY / Delta_E
%   - green = admissibility / REUSE / Lambda
%   - red = composability / PRESERVE / Xi
%   - thin, lightly tinted panel borders
%
% Panel B keeps the frozen seeded mechanism simulation:
%   seed = 20260728
%   audit budgets = [16 32 64 128 256 512 1024]
%   R = 400
%
% Panels C/D are theory/mechanism panels, not empirical validation.
%
% Usage:
%   Figure2_IDA_v4
%   Figure2_IDA_v4('C:\path\to\output')
%
% Output:
%   Figure2_IDA_v4.fig
%   Figure2_IDA_v4.png
%   Figure2_IDA_v4.pdf

close all;

%% ------------------------------------------------------------------------
% 0. STYLE
% -------------------------------------------------------------------------
FONT = 'Arial';

FS_LETTER = 22;
FS_TITLE  = 9;
FS_AXIS   = 9;
FS_TICK   = 9.8;
FS_SMALL  = 9;
FS_TINY   = 9;

navy   = [0.02 0.24 0.63];   % Figure-1 blue
blue   = [0.02 0.29 0.70];

green  = [0.02 0.48 0.20];
teal   = [0.02 0.45 0.38];

red    = [0.82 0.05 0.04];
orange = [0.93 0.27 0.08];

purple = [0.36 0.18 0.62];

grey   = [0.40 0.40 0.40];
dgrey  = [0.22 0.22 0.22];
lgrey  = [0.88 0.89 0.91];

panelBlue  = local_mix(blue,  [1 1 1],0.72);
panelGreen = local_mix(green, [1 1 1],0.72);
panelRed   = local_mix(red,   [1 1 1],0.72);

%% ------------------------------------------------------------------------
% 1. OUTPUT
% -------------------------------------------------------------------------
thisFile = mfilename('fullpath');
if isempty(thisFile)
    scriptDir = pwd;
else
    scriptDir = fileparts(thisFile);
end

if nargin < 1 || isempty(outputDir)
    outputDir = fullfile(scriptDir,'output');
end
if ~exist(outputDir,'dir')
    mkdir(outputDir);
end

%% ------------------------------------------------------------------------
% 2. FROZEN PANEL-B MECHANISM SIMULATION
% -------------------------------------------------------------------------
seed    = 20260728;
budgets = [16 32 64 128 256 512 1024];
R       = 400;

rng(seed,'twister');

% AUC truth for N(1,1) positives versus N(0,1) negatives:
% Phi(1/sqrt(2)) = 0.5*(1+erf(0.5))
auc_truth = 0.5*(1 + erf(0.5));

auc_abs_err = nan(R,numel(budgets));

for i = 1:numel(budgets)
    m = budgets(i);
    nPos = floor(m/2);
    nNeg = m - nPos;

    for r = 1:R
        posScores = randn(nPos,1) + 1;
        negScores = randn(nNeg,1);

        auc_r = local_auc(posScores,negScores);
        auc_abs_err(r,i) = abs(auc_r - auc_truth);
    end
end

auc_mean = mean(auc_abs_err,1,'omitnan');

auc_lo = zeros(size(auc_mean));
auc_hi = zeros(size(auc_mean));
for i = 1:numel(budgets)
    auc_lo(i) = local_quantile(auc_abs_err(:,i),0.10);
    auc_hi(i) = local_quantile(auc_abs_err(:,i),0.90);
end

pfit = polyfit(log10(budgets),log10(auc_mean),1);
auc_slope = pfit(1);

fprintf('\nFigure2_IDA\n');
fprintf('Panel-B seeded slope = %.4f\n',auc_slope);

%% ------------------------------------------------------------------------
% 3. FIGURE CANVAS
% -------------------------------------------------------------------------
fig = figure( ...
    'Color','w', ...
    'Position',[60 45 1300 800], ...
    'Renderer','painters', ...
    'Name','CMDO Figure 2 — evidential order', ...
    'NumberTitle','off');

% Top wide panel
pA = uipanel(fig,'Units','normalized', ...
    'Position',[0.025 0.650 0.950 0.325], ...
    'BackgroundColor','w','BorderType','none');

% Bottom row
pB = uipanel(fig,'Units','normalized', ...
    'Position',[0.025 0.045 0.306 0.575], ...
    'BackgroundColor','w','BorderType','none');

pC = uipanel(fig,'Units','normalized', ...
    'Position',[0.347 0.045 0.306 0.575], ...
    'BackgroundColor','w','BorderType','none');

pD = uipanel(fig,'Units','normalized', ...
    'Position',[0.669 0.045 0.306 0.575], ...
    'BackgroundColor','w','BorderType','none');

%% ========================================================================
% PANEL A — ORDERED EVALUATION SYSTEM
% ========================================================================
axA = axes('Parent',pA,'Units','normalized','Position',[0 0 1 1]);
axis(axA,[0 100 0 32]);
axis(axA,'off');
hold(axA,'on');

local_panel_border(axA,[0.5 0.5 99 31],panelBlue,1.05);

% IMPORTANT: plain panel letter, matching Figure 1.
local_panel_header(axA,'A','The evidential order', ...
    2.0,30.1,navy,FONT,21,14.0);

% -------------------------------------------------------------------------
% Deployment evidence
% -------------------------------------------------------------------------
local_box(axA,[2.2 7.0 13.5 19.8], ...
    [0.995 0.997 1.000],local_mix(blue,[1 1 1],0.35),1.0,0.06);

text(axA,8.95,25.0,'Deployment evidence', ...
    'HorizontalAlignment','center', ...
    'FontName',FONT,'FontSize',FS_SMALL+0.5, ...
    'FontWeight','bold','Color',navy);

obsLabels = {'Inputs','Scores','Predictions','Telemetry'};
obsY = [20.8 17.1 13.4 9.7];

for k = 1:numel(obsLabels)
    local_box(axA,[3.5 obsY(k)-1.25 10.9 2.5], ...
        [1 1 1],local_mix(blue,[1 1 1],0.50),0.75,0.04);

    % small symbol
    switch k
        case 1
            local_database_icon(axA,4.55,obsY(k),0.52,navy);
        case 2
            local_star_icon(axA,4.55,obsY(k),0.45,navy);
        case 3
            local_trend_icon(axA,4.55,obsY(k),0.72,navy);
        case 4
            local_signal_icon(axA,4.55,obsY(k),0.75,navy);
    end

    text(axA,6.0,obsY(k),obsLabels{k}, ...
        'VerticalAlignment','middle', ...
        'FontName',FONT,'FontSize',FS_SMALL, ...
        'Color',dgrey);
end

% -------------------------------------------------------------------------
% Stage 1 — observability
% -------------------------------------------------------------------------
local_capsule(axA,[20.0 15.0 14.5 7.5], ...
    local_mix(blue,[1 1 1],0.10),navy,1.2);

text(axA,27.25,18.75,'Observability', ...
    'HorizontalAlignment','center', ...
    'VerticalAlignment','middle', ...
    'FontName',FONT,'FontSize',FS_TITLE-1, ...
    'FontWeight','bold','Color','w');

text(axA,26.6,24.2,'$\Delta_{\mathcal{E}}$', ...
    'Interpreter','latex', ...
    'HorizontalAlignment','right', ...
    'VerticalAlignment','middle', ...
    'FontSize',FS_SMALL+1.3, ...
    'Color',navy);

text(axA,26.9,24.2,'/ IDENTIFY', ...
    'Interpreter','none', ...
    'HorizontalAlignment','left', ...
    'VerticalAlignment','middle', ...
    'FontName','Arial', ...
    'FontSize',FS_SMALL+1.1, ...
    'FontWeight','bold', ...
    'Color',navy);

% current outcomes / direct estimate
local_box(axA,[21.0 7.4 12.5 5.0], ...
    [0.970 0.995 0.970],local_mix(green,[1 1 1],0.25),0.95,0.05);

text(axA,27.25,9.9,{'Representative','current outcomes'}, ...
    'HorizontalAlignment','center', ...
    'VerticalAlignment','middle', ...
    'FontName',FONT,'FontSize',FS_SMALL, ...
    'FontWeight','bold','Color',[0.08 0.32 0.12]);

local_box(axA,[20.0 1.9 14.5 4.3], ...
    [0.985 0.990 1.000],local_mix(blue,[1 1 1],0.30),0.95,0.05);

text(axA,27.25,4.05,{'Current direct estimate','\pm uncertainty'}, ...
    'Interpreter','tex', ...
    'HorizontalAlignment','center', ...
    'VerticalAlignment','middle', ...
    'FontName',FONT,'FontSize',FS_SMALL, ...
    'FontWeight','bold','Color',navy);

% -------------------------------------------------------------------------
% Stage 2 — admissibility
% -------------------------------------------------------------------------
local_capsule(axA,[45.0 15.0 14.5 7.5], ...
    local_mix(teal,[1 1 1],0.08),[0.00 0.33 0.28],1.2);

text(axA,52.25,18.75,'Admissibility', ...
    'HorizontalAlignment','center', ...
    'VerticalAlignment','middle', ...
    'FontName',FONT,'FontSize',FS_TITLE-1, ...
    'FontWeight','bold','Color','w');

text(axA,48.25,24.2,'\Lambda / REUSE', ...
    'Interpreter','tex', ...
    'HorizontalAlignment','center', ...
    'FontName',FONT,'FontSize',FS_SMALL+1.3, ...
    'FontWeight','bold','Color',green);

% history input
local_box(axA,[45.9 25.4 12.7 4.1], ...
    [0.992 0.987 1.000],local_mix(purple,[1 1 1],0.25),0.95,0.05);

text(axA,52.25,27.45,'Historical evidence', ...
    'HorizontalAlignment','center', ...
    'VerticalAlignment','middle', ...
    'FontName',FONT,'FontSize',FS_SMALL+0.3, ...
    'FontWeight','bold','Color',purple);

% Guarded reuse / direct fallback
local_box(axA,[63.5 14.5 11.0 6.2], ...
    [0.985 1.000 0.995],local_mix(teal,[1 1 1],0.25),0.95,0.05);

text(axA,69.0,17.6,{'Fixed-use','value'}, ...
    'HorizontalAlignment','center', ...
    'VerticalAlignment','middle', ...
    'FontName',FONT,'FontSize',FS_SMALL, ...
    'FontWeight','bold','Color',[0.00 0.34 0.28]);

% -------------------------------------------------------------------------
% Stage 3 — adaptive composability
% -------------------------------------------------------------------------
local_capsule(axA,[76.8 15.0 13.2 7.5], ...
    local_mix(red,[1 1 1],0.03),[0.68 0.02 0.02],1.2);

text(axA,83.4,18.75,{'Adaptive','composability'}, ...
    'HorizontalAlignment','center', ...
    'VerticalAlignment','middle', ...
    'FontName',FONT,'FontSize',FS_TITLE-1.5, ...
    'FontWeight','bold','Color','w');

text(axA,83.4,24.2,'\Xi / PRESERVE', ...
    'Interpreter','tex', ...
    'HorizontalAlignment','center', ...
    'FontName',FONT,'FontSize',FS_SMALL+1.3, ...
    'FontWeight','bold','Color',red);

% Final output
local_box(axA,[91.2 13.8 7.8 9.8], ...
    [1.000 0.990 0.987],local_mix(red,[1 1 1],0.20),1.0,0.05);

text(axA,95.1,18.7,{'Final', 'performance','\pm justified','uncertainty'}, ...
    'Interpreter','tex', ...
    'HorizontalAlignment','center', ...
    'VerticalAlignment','middle', ...
    'FontName',FONT,'FontSize',FS_SMALL, ...
    'FontWeight','bold','Color',red);

% -------------------------------------------------------------------------
% Panel-A arrows
% -------------------------------------------------------------------------
local_arrow(axA,15.9,18.75,19.2,18.75,navy,1.25);   % evidence -> observability
local_arrow(axA,34.8,18.75,44.2,18.75,navy,1.25);   % obs -> admissibility
local_arrow(axA,59.8,18.75,62.8,18.75,green,1.25);  % admissibility -> guarded
local_arrow(axA,74.8,18.75,76.2,18.75,navy,1.25);   % guarded -> adaptive
local_arrow(axA,90.3,18.75,90.9,18.75,red,1.25);    % adaptive -> final

% outcomes branch: representative outcomes augment the evidence channel
local_arrow(axA,27.25,12.8,27.25,14.6,green,1.05);
local_arrow(axA,27.25,7.0,27.25,6.5,navy,1.05);

% history -> admissibility
local_arrow(axA,52.25,25.1,52.25,22.8,purple,1.05);

% current direct estimate supplies same-budget uncertainty to admissibility
plot(axA,[34.6 52.25 52.25],[4.05 4.05 14.4],'--', ...
    'Color',local_mix(teal,[1 1 1],0.10), ...
    'LineWidth',1.0);
local_arrow(axA,52.25,14.4,52.25,14.85,teal,1.0);

%% ========================================================================
% PANEL B — OBSERVABILITY
% ========================================================================
axB0 = axes('Parent',pB,'Units','normalized','Position',[0 0 1 1]);
axis(axB0,[0 1 0 1]);
axis(axB0,'off');
hold(axB0,'on');

local_panel_border(axB0,[0.005 0.005 0.99 0.99],panelBlue,1.05);
local_panel_header(axB0,'B','IDENTIFY | From ambiguity to uncertainty', ...
    0.025,0.955,navy,FONT,20,12.2);

% Top schematic headings
text(axB0,0.14,0.875,'1  Same evidence', ...
    'HorizontalAlignment','center', ...
    'FontName',FONT,'FontSize',8.1,'FontWeight','bold','Color',dgrey);

text(axB0,0.545,0.875,'2  Compatible worlds', ...
    'HorizontalAlignment','center', ...
    'FontName',FONT,'FontSize',8.1,'FontWeight','bold','Color',dgrey);

text(axB0,0.865,0.875,'3  Add outcomes', ...
    'HorizontalAlignment','center', ...
    'FontName',FONT,'FontSize',8.1,'FontWeight','bold','Color',dgrey);

% Shared-score histogram
scoreDemo = [0.08 0.13 0.18 0.22 0.28 0.34 0.40 0.47 ...
             0.53 0.60 0.66 0.72 0.78 0.83 0.88 0.93];

axScore = axes('Parent',pB,'Units','normalized', ...
