function auc = local_auc(posScores,negScores)
scores = [posScores(:); negScores(:)];

ranks = local_tied_rank(double(scores));

nPos = numel(posScores);
nNeg = numel(negScores);

auc = (sum(ranks(1:nPos)) - nPos*(nPos+1)/2) / (nPos*nNeg);
end

function ranks = local_tied_rank(values)
[sortedValues,order] = sort(values);

ranks = zeros(size(values));

i = 1;
while i <= numel(sortedValues)
    j = i;

    while j < numel(sortedValues) && sortedValues(j+1) == sortedValues(i)
        j = j + 1;
    end

    avgRank = (i+j)/2;
    ranks(order(i:j)) = avgRank;

    i = j + 1;
end
end

function q = local_quantile(values,p)
values = sort(values(isfinite(values)));

if isempty(values)
    q = NaN;
    return;
end

idx = 1 + (numel(values)-1)*min(max(p,0),1);
lo  = floor(idx);
hi  = ceil(idx);
a   = idx-lo;

q = (1-a)*values(lo) + a*values(hi);
end

