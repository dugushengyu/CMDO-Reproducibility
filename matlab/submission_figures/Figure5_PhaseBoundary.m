    fsSmall+0.2;

cb.FontSize = ...
    8.2;

% ------------------------------------------------------------
% Shared Lambda label
% ------------------------------------------------------------

text( ...
    axCmaster, ...
    0.47, ...
    0.080, ...
    '\Lambda = B^2/V', ...
    'Units','normalized', ...
    'HorizontalAlignment','center', ...
    'VerticalAlignment','middle', ...
    'FontSize',9.5, ...
    'Color',C_TEXT);



%% ============================================================
% 9. EXPORT
% ============================================================

drawnow;

if strlength(string(opt.OutDir)) == 0
    outdir = fullfile(scriptDir,'output');
else
    outdir = char(opt.OutDir);
end

if ~isfolder(outdir)
    mkdir(outdir);
end

pngPath = ...
    fullfile( ...
    outdir, ...
    'Figure5_PhaseBoundary_Final_3Panel.png');

