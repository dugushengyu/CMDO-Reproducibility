    fullfile( ...
    outdir, ...
    'Figure5_PhaseBoundary_Final_3Panel.pdf');

exportgraphics( ...
    fig, ...
    pngPath, ...
    'Resolution',300, ...
    'BackgroundColor','white');

exportgraphics( ...
    fig, ...
    pdfPath, ...
    'ContentType','vector', ...
    'BackgroundColor','white');

%% ============================================================
% 10. CONSOLE SUMMARY
% ============================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('FIGURE 5 FINAL 3-PANEL ANALYSIS\n');
fprintf('============================================================\n');

fprintf('Input:\n%s\n\n',csvPath);

fprintf('Critical tested Lambda by budget\n\n');

fprintf( ...
    '%8s %10s %10s %10s %10s\n', ...
    'm', ...
