    'DeLong', ...
    'Plug-in');

for ib = 1:nB

    fprintf( ...
        '%8g %10.2f %10.2f %10.2f %10.2f\n', ...
        budgets(ib), ...
        criticalLambda(ib,1), ...
        criticalLambda(ib,2), ...
        criticalLambda(ib,3), ...
        criticalLambda(ib,4));
end

fprintf('\n');

fprintf( ...
    'Shared robust region Lambda <= 1:\n');

fprintf( ...
    'Mean CMDO-U-stat advantage = %.4f pp\n', ...
    overallMeanAdv);

fprintf( ...
    'Paired states CMDO > U-stat = %.2f %%\n', ...
    100*fracPositive);

fprintf('\n');

fprintf('PNG:\n%s\n',pngPath);
fprintf('PDF:\n%s\n',pdfPath);

fprintf('============================================================\n\n');

end

%% ============================================================
% LOCAL FUNCTION
% FULL-WIDTH PHASE MAP
% ============================================================
function plotPhaseMapWide( ...
    ax, ...
    Z, ...
    budgets, ...
    lambdas, ...
    displayLim, ...
    titleText, ...
    fsAxis)

hold(ax,'on');

Zdisplay = ...
    min(max(Z,-displayLim),displayLim);

imagesc( ...
    ax, ...
    1:numel(lambdas), ...
    1:numel(budgets), ...
    Zdisplay);

% Keep useful Lambda ticks now that panel C is full width
preferred = ...
    [0 0.5 1 2 4];

shownVals = ...
    preferred( ...
    ismember(preferred,lambdas));

[~,shownIdx] = ...
    ismember(shownVals,lambdas);

if isempty(shownIdx)

    shownIdx = ...
        1:numel(lambdas);

    shownVals = ...
        lambdas;
end

set( ...
    ax, ...
    'YDir','normal', ...
    'XTick',shownIdx, ...
    'XTickLabel',compose('%g',shownVals), ...
    'YTick',1:numel(budgets), ...
    'YTickLabel',compose('%g',budgets), ...
    'FontSize',fsAxis-0.5, ...
    'TickDir','out', ...
    'LineWidth',0.9);

caxis( ...
    ax, ...
    [-displayLim displayLim]);

box(ax,'off');

% ------------------------------------------------------------
% Zero-excess boundary
% ------------------------------------------------------------

[XI,YI] = meshgrid( ...
    1:numel(lambdas), ...
    1:numel(budgets));

try

    contour( ...
        ax, ...
        XI, ...
        YI, ...
        Z, ...
        [0 0], ...
        'k-', ...
        'LineWidth',1.75);

catch
end

% ------------------------------------------------------------
% Harmful cells
% ------------------------------------------------------------

for ib = 1:size(Z,1)

    for il = 1:size(Z,2)

        if Z(ib,il) > 0

            text( ...
                ax, ...
                il, ...
                ib, ...
                '\times', ...
                'HorizontalAlignment','center', ...
                'VerticalAlignment','middle', ...
                'FontSize',9.4, ...
                'FontWeight','bold', ...
                'Color',[0.22 0.04 0.04]);
        end
    end
end

title( ...
    ax, ...
    titleText, ...
    'FontSize',10.8, ...
    'FontWeight','bold');

end

%% ============================================================
% LOCAL FUNCTION
% BLUE-WHITE-RED DIVERGING COLORMAP
% ============================================================

function cmap = blueWhiteRed(n)

if nargin < 1
    n = 257;
end

n1 = ...
    floor(n/2);

n2 = ...
    n-n1;

blue = ...
    [0.12 0.39 0.72];

white = ...
    [1 1 1];

red = ...
    [0.79 0.18 0.16];

left = [ ...
    linspace(blue(1),white(1),n1)' ...
    linspace(blue(2),white(2),n1)' ...
    linspace(blue(3),white(3),n1)' ];

right = [ ...
    linspace(white(1),red(1),n2)' ...
    linspace(white(2),red(2),n2)' ...
    linspace(white(3),red(3),n2)' ];

cmap = ...
    [left;right];

end

%% ============================================================
% LOCAL FUNCTION
% EMPIRICAL QUANTILE
% ============================================================

function q = empiricalQuantile(x,p)

x = ...
    sort(x(:));

n = ...
    numel(x);

if n == 0

    q = NaN;

    return;
end

if n == 1

    q = x(1);

    return;
end

r = ...
    1+(n-1)*p;

lo = ...
    floor(r);

hi = ...
    ceil(r);

if lo == hi

    q = x(lo);

else

    w = ...
        r-lo;

    q = ...
        (1-w)*x(lo) ...
        + w*x(hi);
end

end

