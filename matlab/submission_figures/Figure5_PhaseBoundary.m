% LEFT-ALIGNED TITLE
% ============================================================

function h = leftTitle( ...
    ax, ...
    str, ...
    fontSize)

h = title( ...
    ax, ...
    str, ...
    'FontSize',fontSize, ...
    'FontWeight','bold');

try

    h.Units = ...
        'normalized';

    p = ...
        h.Position;

    p(1) = ...
        0;

    h.Position = ...
        p;

    h.HorizontalAlignment = ...
        'left';

catch
end

end

