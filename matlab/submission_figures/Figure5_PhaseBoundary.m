    0.175*p(4);

wSmall = ...
    (p(3) ...
    - leftMargin ...
    - rightMargin ...
    - 2*gap) / 3;

hSmall = ...
    p(4) ...
    - bottomMargin ...
    - topMargin;

x1 = ...
    p(1)+leftMargin;

x2 = ...
    x1+wSmall+gap;

x3 = ...
    x2+wSmall+gap;

y0 = ...
    p(2)+bottomMargin;

posC1 = ...
    [x1 y0 wSmall hSmall];

posC2 = ...
    [x2 y0 wSmall hSmall];

posC3 = ...
    [x3 y0 wSmall hSmall];

% ------------------------------------------------------------
% CMDO
% ------------------------------------------------------------

axC1 = axes( ...
    'Parent',fig, ...
    'Position',posC1);

hideToolbarSafe(axC1);

plotPhaseMapWide( ...
    axC1, ...
    Z_CMDO, ...
    budgets, ...
    lambdas, ...
    displayLim, ...
    'CMDO', ...
    fsAxis);

ylabel( ...
    axC1, ...
    'Current-outcome budget, m');

% ------------------------------------------------------------
% U-stat
% ------------------------------------------------------------

axC2 = axes( ...
    'Parent',fig, ...
    'Position',posC2);

hideToolbarSafe(axC2);

plotPhaseMapWide( ...
    axC2, ...
    Z_USTAT, ...
    budgets, ...
    lambdas, ...
    displayLim, ...
    'U-stat', ...
    fsAxis);

ylabel(axC2,'');
set(axC2,'YTickLabel',[]);

% ------------------------------------------------------------
% Plug-in
% ------------------------------------------------------------

axC3 = axes( ...
    'Parent',fig, ...
