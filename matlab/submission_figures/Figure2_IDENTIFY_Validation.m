function Figure2_IDENTIFY_Validation(outputDir, repoRoot)
% FIGURE2_IDENTIFY_VALIDATION
% CMDO Figure 2 — IDENTIFY validation:
% identical monitored evidence can conceal opposite performance.
%
% Scientific role
%   A) Observed model scores in two external ECG cohorts
%   B) Georgia: same observed outputs, opposite compatible performance
%   C) CPSC 2018: same observed outputs, opposite compatible performance
%   D) Frozen U6/U7 direct-audit error versus audit budget, compared with
%      the root-budget prediction for finite-sample uncertainty
%
% IMPORTANT
%   - Panels A-C use frozen U11 score channels and constructed outcome worlds.
%   - Panels A-C do NOT access true U10 target outcomes.
%   - Panels A-C do NOT imply either constructed world is the real clinical world.
%   - Panel D uses frozen U6/U7 current-audit records; it is not a seeded
%     toy simulation and does not use the U11 constructed worlds.
%
% Usage
%   Figure2_IDENTIFY_Validation(outputDir, repoRoot)
close all;

%% ------------------------------------------------------------------------
% 0. STYLE
% -------------------------------------------------------------------------

FONT = 'Arial';

FS_LETTER = 22;
FS_TITLE  = 11.5;
FS_AXIS   = 9.5;
FS_TICK   = 9.0;
FS_SMALL  = 9.2;
FS_TINY   = 8.2;

navy  = [0.02 0.24 0.63];
blue  = [0.02 0.29 0.70];

red   = [0.82 0.05 0.04];
green = [0.02 0.48 0.20];

grey  = [0.42 0.42 0.42];
dgrey = [0.22 0.22 0.22];
lgrey = [0.82 0.82 0.82];

panelBlue = local_mix(blue,[1 1 1],0.72);

%% ------------------------------------------------------------------------
% 1. OUTPUT
% -------------------------------------------------------------------------

thisFile = mfilename('fullpath');

if isempty(thisFile)
    scriptDir = pwd;
else
    scriptDir = fileparts(thisFile);
end

if nargin < 1 || isempty(outputDir)
    outputDir = fullfile(scriptDir,'output');
end

if ~exist(outputDir,'dir')
    mkdir(outputDir);
end

%% ------------------------------------------------------------------------
% 2. LOCATE CMDO REPOSITORY
% -------------------------------------------------------------------------

if nargin < 2 || isempty(repoRoot)
    repoRoot = fileparts(fileparts(scriptDir));
end

assert(isfolder(fullfile(repoRoot,'source_data')), ...
    'Reviewer repository root is invalid.');

fprintf('\n============================================================\n');
fprintf(' CMDO FIGURE 2 — IDENTIFY\n');
fprintf(' Same monitoring, opposite compatible performance\n');
fprintf('============================================================\n');
fprintf('Repository : %s\n',repoRoot);
fprintf('Output     : %s\n',outputDir);

% Reviewer-facing frozen tables are tracked directly in source_data.
addpath(scriptDir);
D = cmdo_submission_load(repoRoot);

%% ------------------------------------------------------------------------
% 3. LOAD FROZEN U11 INFORMATION-CLOSURE WORLDS
% -------------------------------------------------------------------------

U11 = local_load_u11(repoRoot);

% Explicit frozen checks.
assert(U11.georgia.scoreResidual == 0, ...
    'Georgia WORLD+ and WORLD- scores differ.');

assert(U11.cpsc.scoreResidual == 0, ...
    'CPSC WORLD+ and WORLD- scores differ.');

assert(U11.georgia.predictionIdentity, ...
    'Georgia prediction channels differ.');

assert(U11.cpsc.predictionIdentity, ...
    'CPSC prediction channels differ.');

assert(abs(U11.georgia.prevalencePlus - ...
           U11.georgia.prevalenceMinus) < 1e-12, ...
    'Georgia prevalence is not matched.');

assert(abs(U11.cpsc.prevalencePlus - ...
           U11.cpsc.prevalenceMinus) < 1e-12, ...
    'CPSC prevalence is not matched.');

%% ------------------------------------------------------------------------
% 4. FROZEN CURRENT-AUDIT CONVERGENCE
% -------------------------------------------------------------------------
%
% Once representative current outcomes are available, IDENTIFY predicts
% ordinary finite-sample uncertainty.  For bounded performance quantities
% (including balanced AUC), the expected direct-estimation error should
% contract at the root-budget order m^{-1/2}.
%
% Here we test that consequence on the frozen U6/U7 audit records rather
% than on the seeded Figure-2 mechanism simulation.
%

local_require_vars( ...
    D.u6_state, ...
    {'budget','direct_mae'}, ...
    'U6 state table');

metricCol7S = ...
    local_find_var(D.u7_state,{'metric'});

if isempty(metricCol7S)

    error('U7 state table missing metric.');

end

S7AUC = ...
    D.u7_state( ...
    string(D.u7_state.(metricCol7S))=="AUC",:);

local_require_vars( ...
    S7AUC, ...
    {'budget','direct_mae'}, ...
    'U7 AUC state table');

bud6 = ...
    sort(unique(double(D.u6_state.budget)))';

bud7 = ...
    sort(unique(double(S7AUC.budget)))';

u6MeanDirect = nan(size(bud6));
u6LoDirect   = nan(size(bud6));
u6HiDirect   = nan(size(bud6));

u7MeanDirect = nan(size(bud7));
u7LoDirect   = nan(size(bud7));
u7HiDirect   = nan(size(bud7));

for i = 1:numel(bud6)

    v = double( ...
        D.u6_state.direct_mae( ...
        double(D.u6_state.budget)==bud6(i)));

    v = v(isfinite(v));

    u6MeanDirect(i) = mean(v,'omitnan');
    u6LoDirect(i)   = local_quantile(v,0.10);
    u6HiDirect(i)   = local_quantile(v,0.90);

end

for i = 1:numel(bud7)

    v = double( ...
        S7AUC.direct_mae( ...
        double(S7AUC.budget)==bud7(i)));

    v = v(isfinite(v));

    u7MeanDirect(i) = mean(v,'omitnan');
    u7LoDirect(i)   = local_quantile(v,0.10);
    u7HiDirect(i)   = local_quantile(v,0.90);

end

m6fit = ...
    isfinite(bud6) & ...
    isfinite(u6MeanDirect) & ...
    bud6>0 & ...
    u6MeanDirect>0;

m7fit = ...
    isfinite(bud7) & ...
    isfinite(u7MeanDirect) & ...
    bud7>0 & ...
    u7MeanDirect>0;

assert(nnz(m6fit)>=3, ...
    'Insufficient U6 budgets for log-log slope.');

assert(nnz(m7fit)>=3, ...
    'Insufficient U7 budgets for log-log slope.');

p6 = polyfit( ...
    log10(bud6(m6fit)), ...
    log10(u6MeanDirect(m6fit)), ...
    1);

p7 = polyfit( ...
    log10(bud7(m7fit)), ...
    log10(u7MeanDirect(m7fit)), ...
    1);

u6Slope = p6(1);
u7Slope = p7(1);

% Root-budget theory lines, anchored to each empirical curve at its
% smallest evaluated audit budget.  These are rate references, not fits.
u6RootRef = ...
    u6MeanDirect(find(m6fit,1,'first')) .* ...
    (bud6 ./ bud6(find(m6fit,1,'first'))).^(-0.5);

u7RootRef = ...
    u7MeanDirect(find(m7fit,1,'first')) .* ...
    (bud7 ./ bud7(find(m7fit,1,'first'))).^(-0.5);

fprintf('\n--- IDENTIFY FROZEN AUDIT-CONVERGENCE ---\n');
fprintf('U6 direct-audit slope = %.6f\n',u6Slope);
fprintf('U7 direct-audit slope = %.6f\n',u7Slope);

