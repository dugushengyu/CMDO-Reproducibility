function S = local_parse_u11_pair(Tp,Tm,nameStr)

local_require_vars( ...
    Tp, ...
    {'score_af','predicted_af','synthetic_outcome'}, ...
    [nameStr ' WORLD+']);

local_require_vars( ...
    Tm, ...
    {'score_af','predicted_af','synthetic_outcome'}, ...
    [nameStr ' WORLD-']);

sp = double(Tp.score_af(:));
sm = double(Tm.score_af(:));

pp = double(Tp.predicted_af(:));
pm = double(Tm.predicted_af(:));

ypRaw = double(Tp.synthetic_outcome(:));
ymRaw = double(Tm.synthetic_outcome(:));

assert( ...
    numel(sp)==numel(sm), ...
    'U11 paired worlds have different lengths.');

% If record IDs are available, verify that those channels also match.
if ismember('record_id',Tp.Properties.VariableNames) && ...
        ismember('record_id',Tm.Properties.VariableNames)

    ridP = string(Tp.record_id);
    ridM = string(Tm.record_id);

    assert( ...
        isequal(ridP,ridM), ...
        'U11 record_id channels differ.');

end

scoreResidual = max(abs(sp-sm),[],'omitnan');

predictionIdentity = isequal(pp,pm);

% Preserve original frozen ordering for the monitoring-stream panel.
S.scoreRaw = sp;

% Sort only for the compatible-world visualization.
[scoreSorted,ord] = sort(sp,'ascend');

yp = ypRaw(ord);
ym = ymRaw(ord);

S.name = nameStr;

S.n = numel(sp);

S.score = scoreSorted;

S.yPlus = yp;
S.yMinus = ym;

S.prevalencePlus = mean(ypRaw,'omitnan');
S.prevalenceMinus = mean(ymRaw,'omitnan');

S.aucPlus = local_auc_rank(sp,ypRaw);
S.aucMinus = local_auc_rank(sm,ymRaw);

S.aucGap = abs( ...
    S.aucPlus - S.aucMinus);

S.scoreResidual = scoreResidual;

S.predictionIdentity = predictionIdentity;

end

