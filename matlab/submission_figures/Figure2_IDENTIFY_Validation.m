end

end

function q = local_quantile(values,p)

values = sort(double(values(:)));
values = values(isfinite(values));

if isempty(values)

    q = NaN;
    return;

end

idx = ...
    1 + ...
    (numel(values)-1) .* ...
    min(max(p,0),1);

lo = floor(idx);
hi = ceil(idx);

a = idx-lo;

q = ...
    (1-a).*values(lo) + ...
    a.*values(hi);

end

