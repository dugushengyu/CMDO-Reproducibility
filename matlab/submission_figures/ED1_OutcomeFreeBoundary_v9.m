function rho = local_spearman(x,y)

x = double(x(:));
y = double(y(:));

valid = ...
    isfinite(x) & ...
    isfinite(y);

x = x(valid);
y = y(valid);

if numel(x)<3
    rho = NaN;
    return;
end

rx = local_tied_rank(x);
ry = local_tied_rank(y);

C = corrcoef(rx,ry);

if numel(C)<4
    rho = NaN;
else
    rho = C(1,2);
end

end


function r = local_tied_rank(v)

v = double(v(:));

n = numel(v);

[sv,ord] = sort(v,'ascend');

r = zeros(n,1);

i = 1;

while i<=n

    j = i;

    while ...
            j<n && ...
            sv(j+1)==sv(i)

        j = j+1;

    end

    r(ord(i:j)) = ...
        0.5*(i+j);

    i = j+1;

end

end


