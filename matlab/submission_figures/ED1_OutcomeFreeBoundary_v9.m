function stageDir = local_extract_canonical(dataDir,cacheDir,zipName)

zipPath = ...
    cmdo.find_unique_file(dataDir,zipName);

if ~exist(zipPath,'file')
    error('Missing canonical archive: %s',zipPath);
end

stageDir = ...
    fullfile( ...
        cacheDir, ...
        erase(zipName,'.zip'));

ready = ...
    fullfile(stageDir,'.ready');

if ~exist(ready,'file')

    if exist(stageDir,'dir')
        rmdir(stageDir,'s');
    end

    mkdir(stageDir);

    unzip(zipPath,stageDir);

    fid = fopen(ready,'w');

    if fid>0
        fprintf(fid,'ready\n');
        fclose(fid);
    end

end

end


