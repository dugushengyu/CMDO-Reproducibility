function U4C = local_load_u4c(dataDir,cacheDir)
% Frozen U4C canonical archive.

stageDir = dataDir;

A = local_read_canonical( ...
    stageDir, ...
    'StageU4C_Audit_State_Results_v1.1.csv');

F = local_read_canonical( ...
    stageDir, ...
    'StageU4C_Component_Fits_v1.1.csv');

P = local_read_canonical( ...
    stageDir, ...
    'StageU4C_Component_Trajectory_Predictions_v1.1.csv');

E = local_read_canonical( ...
    stageDir, ...
    'StageU4C_Evidence_Expiry_Map_v1.1.csv');

targetOrder = [ ...
    "EMNIST_DIGITS", ...
    "FL", ...
    "GENRE_facetoface", ...
    "GENRE_letters", ...
    "GENRE_nineeleven", ...
    "GENRE_oup", ...
    "GENRE_verbatim", ...
    "IL", ...
    "NY", ...
    "QMNIST_TEST50K", ...
    "SVHN", ...
    "TX", ...
    "USPS"];

budgets = sort(unique(double(P.budget)));

deltaMat = nan(numel(targetOrder),numel(budgets));

for i = 1:numel(targetOrder)

    for j = 1:numel(budgets)

        mask = ...
            string(P.target)==targetOrder(i) & ...
            double(P.budget)==budgets(j);

        if any(mask)

            uerr = abs( ...
                double(P.component_pred(mask)) - ...
                double(P.truth_direct_mae(mask)));

            rerr = abs( ...
                double(P.rootn_pred(mask)) - ...
                double(P.truth_direct_mae(mask)));

            deltaMat(i,j) = ...
                local_nanmean(uerr-rerr);

        end

    end

end

rootLate = double(F.rootn_late_mae);
ruleLate = double(F.component_late_mae);

predExpiry = ...
    min( ...
        max( ...
            double(E.predicted_expiry_budget_from_budget8), ...
            8), ...
        256);

empExpiry = ...
    min( ...
        max( ...
            double(E.empirical_expiry_budget), ...
            8), ...
        256);

U4C.targets = strings(numel(targetOrder),1);

for i = 1:numel(targetOrder)
    U4C.targets(i) = string(local_short_u4(targetOrder(i)));
end

U4C.budgets = budgets;
U4C.deltaMat = deltaMat;

U4C.rootLate = rootLate;
U4C.ruleLate = ruleLate;

U4C.predExpiry = predExpiry;
U4C.empExpiry  = empExpiry;

U4C.nRuleBetterLate = ...
    nnz(ruleLate < rootLate);

U4C.nRootBetterLate = ...
    nnz(rootLate < ruleLate);

U4C.audit = A;

assert( ...
    numel(U4C.targets)==13, ...
    'Expected 13 frozen U4C targets.');

assert( ...
    numel(rootLate)==13, ...
    'Expected 13 U4C late-budget comparisons.');

assert( ...
    numel(predExpiry)==13, ...
    'Expected 13 U4C expiry records.');

end


function U5B = local_load_u5b(dataDir,cacheDir)
% Frozen U5B canonical archive.

stageDir = dataDir;

S = local_read_canonical( ...
    stageDir, ...
    'StageU5B_Audit_State_Results_v1.0.csv');

required = { ...
    'mean_sentinel_bias_sq', ...
    'mean_sentinel_weight', ...
    'transport_abs_error'};

for i = 1:numel(required)

    if ~ismember(required{i},S.Properties.VariableNames)

        error( ...
            'U5B canonical table missing field: %s', ...
            required{i});

    end

end

U5B.bias2 = ...
    double(S.mean_sentinel_bias_sq);

U5B.weight = ...
    double(S.mean_sentinel_weight);

U5B.transport = ...
    double(S.transport_abs_error);

U5B.state = S;

end


