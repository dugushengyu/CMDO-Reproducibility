    dir(fullfile(stageDir,'**',fileName));

if isempty(hits)

    error( ...
        'Canonical CSV not found after extraction: %s', ...
        fileName);

end

T = readtable( ...
    fullfile(hits(1).folder,hits(1).name), ...
    'VariableNamingRule','preserve');

end


