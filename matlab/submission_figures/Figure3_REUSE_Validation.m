function local_fit_band(ax,x,y)

x = double(x(:));
y = double(y(:));

m = ...
    isfinite(x) & ...
    isfinite(y);

x = x(m);
y = y(m);

n = numel(x);

if n < 3
    return;
end

X = [ones(n,1),x];

beta = X\y;

xg = ...
    linspace( ...
    min(x),max(x),180)';

yg = ...
    beta(1) + ...
    beta(2).*xg;

res = ...
    y-X*beta;

df = ...
    max(n-2,1);

s2 = ...
    sum(res.^2)./df;

xm = mean(x);

sxx = ...
    sum((x-xm).^2);

if ~isfinite(sxx) || sxx<=0
    sxx = eps;
end

se = ...
    sqrt( ...
    s2 .* ...
    (1/n + ...
    (xg-xm).^2./sxx));

tc = ...
    local_tcritical95(df);

lo = yg-tc.*se;
hi = yg+tc.*se;

fill( ...
    ax, ...
    [xg;flipud(xg)], ...
    [lo;flipud(hi)], ...
    [0.72 0.72 0.72], ...
    'FaceAlpha',0.20, ...
    'EdgeColor','none', ...
    'HandleVisibility','off');

plot( ...
    ax,xg,yg, ...
    'k-', ...
    'LineWidth',1.15, ...
    'HandleVisibility','off');

end

function tcrit = local_tcritical95(df)

if df<=0
    tcrit = 1.96;
    return;
end

b = ...
    betaincinv( ...
    0.05, ...
    df/2, ...
    0.5);

tcrit = ...
    sqrt( ...
    df.*(1-b)./b);

end

