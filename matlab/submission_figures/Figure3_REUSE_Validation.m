function Figure3_REUSE_Validation(outputDir, repoRoot)
% FIGURE3_REUSE_VALIDATION
% CMDO Figure 3 — REUSE validation
%
% Final scientific role:
%   A) Frozen confirmation in cross-domain and clinical settings
%   B) Current-audit discrepancy tracks later-revealed historical mismatch |B|
%   C) The REUSE admissibility boundary separates observed benefit from harm
%   D) Predicted fixed-use risk is compared directly with observed risk
%
% Usage:
%   Figure3_REUSE_Validation(outputDir, repoRoot)
close all;

%% ------------------------------------------------------------------------
% 0. STYLE
% -------------------------------------------------------------------------

FONT = 'Arial';

FS_LETTER = 21;
FS_TITLE  = 10.5;
FS_AXIS   = 9.0;
FS_TICK   = 8.6;
FS_SMALL  = 8.5;
FS_TINY   = 7.6;

navy   = [0.02 0.24 0.63];
blue   = [0.02 0.29 0.70];

green  = [0.02 0.48 0.20];
teal   = [0.02 0.45 0.38];

orange = [0.93 0.27 0.08];
red    = [0.82 0.05 0.04];
purple = [0.43 0.17 0.70];

grey   = [0.42 0.42 0.42];
dgrey  = [0.22 0.22 0.22];

panelGreen = local_mix(green,[1 1 1],0.74);

clinicalColor = [0.05 0.52 0.20];

stageOrder = ["U6","U7","U8","U9A","U9B"];

stageLabels = { ...
    'Cross-domain', ...
    'Clinical', ...
    'Temporal', ...
    'External bridge', ...
    'External system'};

stageColors = [ ...
    0.02 0.29 0.70; ...
    0.02 0.48 0.20; ...
    0.43 0.17 0.70; ...
    0.93 0.45 0.08; ...
    0.82 0.05 0.04];

stageMarkers = {'o','s','d','^','p'};

familyOrder = [ ...
    "ACS_PUBLIC_COVERAGE_2024", ...
    "MEDICAL_DERMOSCOPY", ...
    "NATURAL_IMAGE"];

familyColors = [ ...
    0.1216 0.4667 0.7059; ...
    1.0000 0.4980 0.0549; ...
    0.8392 0.1529 0.1569];

%% ------------------------------------------------------------------------
% 1. OUTPUT / REPOSITORY
% -------------------------------------------------------------------------

thisFile = mfilename('fullpath');

if isempty(thisFile)
    scriptDir = pwd;
else
    scriptDir = fileparts(thisFile);
end

if nargin < 1 || isempty(outputDir)
    outputDir = fullfile(scriptDir,'output');
end

if ~exist(outputDir,'dir')
    mkdir(outputDir);
end

if nargin < 2 || isempty(repoRoot)
    repoRoot = fileparts(fileparts(scriptDir));
end

assert(isfolder(fullfile(repoRoot,'source_data')), ...
    'Reviewer repository root is invalid.');

addpath(scriptDir);

fprintf('\n============================================================\n');
fprintf(' CMDO FIGURE 3 — REUSE\n');
fprintf(' REUSE theory tested against frozen deployment states\n');
fprintf('============================================================\n');
fprintf('Repository : %s\n',repoRoot);
fprintf('Output     : %s\n',outputDir);

%% ------------------------------------------------------------------------
% 2. LOAD FROZEN U6 / U7 TABLES
% -------------------------------------------------------------------------

D = cmdo_submission_load(repoRoot);

%% ------------------------------------------------------------------------
% 3. U6 CROSS-DOMAIN CONFIRMATION
% -------------------------------------------------------------------------

U6raw = D.u6_target;

u6Observer = double(U6raw.mae);
u6Direct   = double(U6raw.direct_mae);

u6RelGain = ...
    100 .* double(U6raw.gain_vs_full_direct) ./ u6Direct;

u6PooledObserver = ...
    mean(double(D.u6_state.mae),'omitnan');

u6PooledDirect = ...
    mean(double(D.u6_state.direct_mae),'omitnan');

u6PooledGain = ...
    100 .* ...
    (u6PooledDirect-u6PooledObserver) ./ ...
    u6PooledDirect;

% Sort only for display.
[u6DisplayGain,~] = ...
    sort(u6RelGain,'descend');

%% ------------------------------------------------------------------------
% 4. U7 CLINICAL CONFIRMATION
% -------------------------------------------------------------------------

metricCol7T = ...
    local_find_var(D.u7_target,{'metric'});

if isempty(metricCol7T)
    error('U7 target table missing metric.');
end

U7 = ...
    D.u7_target( ...
    string(D.u7_target.(metricCol7T))=="AUC",:);

u7RelGain = ...
    100 .* double(U7.gain) ./ ...
    double(U7.direct_mae);

[u7DisplayGain,~] = ...
    sort(u7RelGain,'descend');

metricCol7M = ...
    local_find_var(D.u7_metric,{'metric'});

rowAUC = ...
    find( ...
    string(D.u7_metric.(metricCol7M))=="AUC", ...
    1,'first');

if isempty(rowAUC)
    error('AUC row absent in U7 metric table.');
end

u7PooledGain = ...
    100 .* double( ...
    D.u7_metric.relative_gain(rowAUC));

metricCol7S = ...
    local_find_var(D.u7_state,{'metric'});

S7AUC = ...
    D.u7_state( ...
    string(D.u7_state.(metricCol7S))=="AUC",:);

%% ------------------------------------------------------------------------
% 5. AUDIT-MISMATCH / HISTORICAL-ERROR RELATION
% -------------------------------------------------------------------------

maxBudget6 = ...
    max(double(D.u6_state.budget),[],'omitnan');

M6 = ...
    D.u6_state( ...
    double(D.u6_state.budget)==maxBudget6,:);

x6 = double(M6.mean_sensor_abs_gap);
y6 = double(M6.transport_abs_error);
fam6 = string(M6.family);

rho6 = local_spearman(x6,y6);

maxBudget7 = ...
    max(double(S7AUC.budget),[],'omitnan');

M7 = ...
    S7AUC( ...
    double(S7AUC.budget)==maxBudget7,:);

x7 = double(M7.mean_sensor_gap);
y7 = double(M7.transport_abs_error);

rho7 = local_spearman(x7,y7);

%% ------------------------------------------------------------------------
% 6. 185-STATE EVIDENCE-ADMISSIBILITY SYNTHESIS
% -------------------------------------------------------------------------

statePath = ...
    fullfile( ...
    repoRoot, ...
    'source_data', ...
    'figure6_admissibility', ...
    'CMDO_Admissibility_State_MSE_Audit.csv');

if ~isfile(statePath)

    error( ...
        'Missing 185-state synthesis file:\n%s', ...
        statePath);

end

T = readtable(statePath);

local_require_vars( ...
    T, ...
    {'stage', ...
     'mean_weight', ...
     'lambda_ean', ...
     'mse_gain_pct', ...
     'scalar_risk_ratio_at_meanweight'}, ...
    '185-state synthesis');

stageName = string(T.stage);

wState = ...
    double(T.mean_weight);

lambdaState = ...
    double(T.lambda_ean);

gObserved = ...
    double(T.mse_gain_pct);

riskReconstructed = ...
    (1-wState).^2 + ...
    lambdaState .* wState.^2;

gPredicted = ...
    100 .* (1-riskReconstructed);

% Express the observed statewise MSE in the same normalized-risk
% coordinates as Eq. (2): R/V = 1 - gain/100.
riskObserved = ...
    1 - gObserved./100;

storedRatio = ...
    double(T.scalar_risk_ratio_at_meanweight);

ratioResidual = ...
    max( ...
    abs( ...
    riskReconstructed-storedRatio), ...
    [],'omitnan');

assert( ...
    height(T)==185, ...
    'Expected 185 frozen states.');

assert( ...
    ratioResidual < 1e-10, ...
    '185-state scalar-risk reconstruction mismatch.');

signConcordant = ...
    local_sign_concordance( ...
    gPredicted,gObserved);

signN = nnz(signConcordant);

rho185 = ...
    local_spearman( ...
    gPredicted,gObserved);

stageMedPred = ...
    nan(numel(stageOrder),1);

stageMedObs = ...
    nan(numel(stageOrder),1);

for s = 1:numel(stageOrder)

    m = ...
        stageName==stageOrder(s);

    stageMedPred(s) = ...
        median(gPredicted(m),'omitnan');

    stageMedObs(s) = ...
        median(gObserved(m),'omitnan');

end

% The affine conversion preserves the stage medians exactly.
stageMedPredRisk = ...
    1 - stageMedPred./100;

stageMedObsRisk = ...
    1 - stageMedObs./100;

%% ------------------------------------------------------------------------
% 7. FIGURE CANVAS
% -------------------------------------------------------------------------

fig = figure( ...
    'Color','w', ...
    'Position',[60 45 1000 800], ...
    'Renderer','painters', ...
    'Name','CMDO Figure 3 — REUSE', ...
    'NumberTitle','off');

pA = uipanel( ...
    fig, ...
    'Units','normalized', ...
    'Position',[0.025 0.515 0.465 0.460], ...
    'BackgroundColor','w', ...
    'BorderType','none');

pB = uipanel( ...
    fig, ...
    'Units','normalized', ...
    'Position',[0.510 0.515 0.465 0.460], ...
    'BackgroundColor','w', ...
    'BorderType','none');

pC = uipanel( ...
    fig, ...
    'Units','normalized', ...
    'Position',[0.025 0.040 0.465 0.445], ...
    'BackgroundColor','w', ...
    'BorderType','none');

pD = uipanel( ...
    fig, ...
    'Units','normalized', ...
    'Position',[0.510 0.040 0.465 0.445], ...
    'BackgroundColor','w', ...
    'BorderType','none');

%% ========================================================================
% PANEL A — FROZEN CONFIRMATION
% ========================================================================

axA0 = axes( ...
    'Parent',pA, ...
    'Units','normalized', ...
    'Position',[0 0 1 1]);

axis(axA0,[0 1 0 1]);
axis(axA0,'off');
hold(axA0,'on');

local_panel_border( ...
    axA0, ...
    [0.005 0.005 0.99 0.99], ...
    panelGreen, ...
    1.05);

local_panel_header( ...
    axA0, ...
    'A', ...
    'Frozen confirmation', ...
    0.025,0.955, ...
    green,FONT, ...
    FS_LETTER,FS_TITLE);

% Shared y limits for direct comparison.
allConfirmationGain = ...
    [u6DisplayGain(:);u7DisplayGain(:)];

% Cross-version-safe finite-value handling
validConfirmationGain = ...
    allConfirmationGain(isfinite(allConfirmationGain));

if isempty(validConfirmationGain)
    error('No finite confirmation-gain values were found.');
end

yMinA = ...
    min(0,min(validConfirmationGain));

yMaxA = ...
    max(validConfirmationGain);

ySpanA = ...
    max(yMaxA-yMinA,1);

yLimA = [ ...
    yMinA-0.08*ySpanA, ...
    yMaxA+0.18*ySpanA];

% U6
axA1 = axes( ...
    'Parent',pA, ...
    'Units','normalized', ...
    'Position',[0.120 0.205 0.365 0.610]);

hold(axA1,'on');

plot( ...
    axA1, ...
    [0.5 16.5], ...
    [0 0], ...
    '--', ...
    'Color',[0.45 0.45 0.45], ...
    'LineWidth',0.8);

scatter( ...
    axA1, ...
    1:16, ...
    u6DisplayGain, ...
    42, ...
    'o', ...
    'filled', ...
    'MarkerFaceColor',blue, ...
    'MarkerEdgeColor','w', ...
    'LineWidth',0.5);

set( ...
    axA1, ...
    'XLim',[0.5 16.5], ...
    'YLim',yLimA, ...
    'XTick',[1 8 16], ...
    'FontName',FONT, ...
    'FontSize',FS_TICK, ...
    'TickDir','out', ...
    'LineWidth',0.75, ...
    'Box','off');

xlabel( ...
    axA1, ...
    'Target', ...
    'FontName',FONT, ...
    'FontSize',FS_AXIS);

ylabel( ...
    axA1, ...
    'Relative MAE gain vs direct (%)', ...
    'FontName',FONT, ...
    'FontSize',FS_AXIS);

title( ...
    axA1, ...
    'Cross-domain', ...
    'FontName',FONT, ...
    'FontSize',FS_SMALL+0.4, ...
    'FontWeight','bold');

text( ...
    axA1, ...
    0.96,0.95, ...
    sprintf('16/16\n+%.2f%%',u6PooledGain), ...
    'Units','normalized', ...
    'HorizontalAlignment','right', ...
    'VerticalAlignment','top', ...
    'FontName',FONT, ...
    'FontSize',FS_SMALL, ...
    'FontWeight','bold', ...
    'Color',blue);

% U7
axA2 = axes( ...
    'Parent',pA, ...
    'Units','normalized', ...
    'Position',[0.585 0.205 0.365 0.610]);

hold(axA2,'on');

plot( ...
    axA2, ...
    [0.5 16.5], ...
    [0 0], ...
    '--', ...
    'Color',[0.45 0.45 0.45], ...
    'LineWidth',0.8);

scatter( ...
    axA2, ...
    1:16, ...
    u7DisplayGain, ...
    42, ...
    's', ...
    'filled', ...
    'MarkerFaceColor',clinicalColor, ...
    'MarkerEdgeColor','w', ...
    'LineWidth',0.5);

set( ...
    axA2, ...
    'XLim',[0.5 16.5], ...
    'YLim',yLimA, ...
    'XTick',[1 8 16], ...
    'FontName',FONT, ...
    'FontSize',FS_TICK, ...
    'TickDir','out', ...
    'LineWidth',0.75, ...
    'Box','off');

xlabel( ...
    axA2, ...
    'Clinical stratum', ...
    'FontName',FONT, ...
    'FontSize',FS_AXIS);
ylabel( ...
    axA2, ...
    'MAE improvement vs direct (%)', ...
    'FontName',FONT, ...
    'FontSize',FS_AXIS);

title( ...
    axA2, ...
    'Clinical transition', ...
    'FontName',FONT, ...
    'FontSize',FS_SMALL+0.4, ...
    'FontWeight','bold');

text( ...
    axA2, ...
    0.96,0.95, ...
    sprintf('16/16\n+%.2f%%',u7PooledGain), ...
    'Units','normalized', ...
    'HorizontalAlignment','right', ...
    'VerticalAlignment','top', ...
    'FontName',FONT, ...
    'FontSize',FS_SMALL, ...
    'FontWeight','bold', ...
    'Color',clinicalColor);

%% ========================================================================
% PANEL B — AUDIT DISCREPANCY TRACKS HISTORICAL MISMATCH |B|
% ========================================================================

axB0 = axes( ...
    'Parent',pB, ...
    'Units','normalized', ...
    'Position',[0 0 1 1]);

axis(axB0,[0 1 0 1]);
axis(axB0,'off');
hold(axB0,'on');

local_panel_border( ...
    axB0, ...
    [0.005 0.005 0.99 0.99], ...
    panelGreen, ...
    1.05);

local_panel_header( ...
    axB0, ...
    'B', ...
    'Current audit tracks historical mismatch', ...
    0.025,0.955, ...
    green,FONT, ...
    FS_LETTER,FS_TITLE);

% U6
axB1 = axes( ...
    'Parent',pB, ...
    'Units','normalized', ...
    'Position',[0.115 0.205 0.365 0.610]);

hold(axB1,'on');

local_fit_band(axB1,x6,y6);

familyLabels = { ...
    'ACS 2024', ...
    'Dermoscopy', ...
    'Natural image'};

hFam = gobjects(numel(familyOrder),1);

for f = 1:numel(familyOrder)

    m = fam6==familyOrder(f);

    hFam(f) = scatter( ...
        axB1, ...
        x6(m), ...
        y6(m), ...
        30, ...
        'o', ...
        'filled', ...
        'MarkerFaceColor',familyColors(f,:), ...
        'MarkerEdgeColor','w', ...
        'LineWidth',0.45, ...
        'DisplayName',familyLabels{f});

end

set( ...
    axB1, ...
    'FontName',FONT, ...
    'FontSize',FS_TICK, ...
    'TickDir','out', ...
    'LineWidth',0.75, ...
    'Box','off');

xlabel( ...
    axB1, ...
    'Current-audit discrepancy, \delta_{audit}', ...
    'FontName',FONT, ...
    'FontSize',FS_AXIS);

ylabel( ...
    axB1, ...
    'Historical mismatch, |B|', ...
    'FontName',FONT, ...
    'FontSize',FS_AXIS);

title( ...
    axB1, ...
    sprintf('Cross-domain   \\rho = %.2f',rho6), ...
    'Interpreter','tex', ...
    'FontName',FONT, ...
    'FontSize',FS_SMALL, ...
    'FontWeight','bold');

legend( ...
    axB1, ...
    hFam, ...
    familyLabels, ...
    'Location','southeast', ...
    'Box','off', ...
    'FontName',FONT, ...
    'FontSize',6.3);

% U7
axB2 = axes( ...
    'Parent',pB, ...
    'Units','normalized', ...
    'Position',[0.600 0.205 0.350 0.610]);

hold(axB2,'on');

local_fit_band(axB2,x7,y7);

scatter( ...
    axB2, ...
    x7,y7, ...
    32, ...
    's', ...
    'filled', ...
    'MarkerFaceColor',clinicalColor, ...
    'MarkerEdgeColor','w', ...
    'LineWidth',0.45);

set( ...
    axB2, ...
    'FontName',FONT, ...
    'FontSize',FS_TICK, ...
    'TickDir','out', ...
    'LineWidth',0.75, ...
    'Box','off');

xlabel( ...
    axB2, ...
    'Current-audit discrepancy, \delta_{audit}', ...
    'FontName',FONT, ...
    'FontSize',FS_AXIS);

ylabel( ...
    axB2, ...
    'Historical mismatch, |B|', ...
    'FontName',FONT, ...
    'FontSize',FS_AXIS);

title( ...
    axB2, ...
    sprintf('Clinical   \\rho = %.2f',rho7), ...
    'Interpreter','tex', ...
    'FontName',FONT, ...
    'FontSize',FS_SMALL, ...
    'FontWeight','bold');

%% ========================================================================
% PANEL C — THEORY BOUNDARY VERSUS OBSERVED BENEFIT / HARM
% ========================================================================

axC0 = axes( ...
    'Parent',pC, ...
    'Units','normalized', ...
    'Position',[0 0 1 1]);

axis(axC0,[0 1 0 1]);
axis(axC0,'off');
hold(axC0,'on');

local_panel_border( ...
    axC0, ...
    [0.005 0.005 0.99 0.99], ...
    panelGreen, ...
    1.05);

local_panel_header( ...
    axC0, ...
    'C', ...
    'Admissibility geometry separates benefit from harm', ...
    0.025,0.955, ...
    green,FONT, ...
    FS_LETTER,FS_TITLE);

axC = axes( ...
    'Parent',pC, ...
    'Units','normalized', ...
    'Position',[0.175 0.205 0.755 0.615]);

hold(axC,'on');

% -------------------------------------------------------------------------
% Theory boundary
%
% Eq. (2) gives beneficial fixed reuse when
%   (1-w)^2 + Lambda*w^2 < 1,
% i.e. for w>0:
%   w < 2/(1+Lambda).
%
% The equation itself is kept out of the artwork and belongs in the caption.
% -------------------------------------------------------------------------

validGeom = ...
    isfinite(lambdaState) & ...
    lambdaState>0 & ...
    isfinite(wState) & ...
    wState>=0 & ...
    wState<=1 & ...
    isfinite(gObserved);

lambdaValid = ...
    lambdaState(validGeom);

if isempty(lambdaValid)
    error('No finite positive Lambda values are available for Panel C.');
end

logMinC = floor(log10(min(lambdaValid)));
logMaxC = ceil(log10(max(lambdaValid)));

if logMinC==logMaxC
    logMinC = logMinC-1;
    logMaxC = logMaxC+1;
end

xMinC = 10.^logMinC;
xMaxC = 10.^logMaxC;

lambdaLine = ...
    logspace(logMinC,logMaxC,600);

wBoundary = ...
    min(2./(1+lambdaLine),1);

% Theory-predicted beneficial region.
patch( ...
    axC, ...
    [lambdaLine fliplr(lambdaLine)], ...
    [zeros(size(wBoundary)) fliplr(wBoundary)], ...
    local_mix(green,[1 1 1],0.87), ...
    'EdgeColor','none', ...
    'FaceAlpha',0.92, ...
    'HandleVisibility','off');

% Theory-predicted harmful region.
patch( ...
    axC, ...
    [lambdaLine fliplr(lambdaLine)], ...
    [wBoundary fliplr(ones(size(wBoundary)))], ...
    local_mix(red,[1 1 1],0.91), ...
    'EdgeColor','none', ...
    'FaceAlpha',0.92, ...
    'HandleVisibility','off');

plot( ...
    axC, ...
    lambdaLine,wBoundary, ...
    '--', ...
    'Color',[0.18 0.18 0.18], ...
    'LineWidth',1.20, ...
    'HandleVisibility','off');

% -------------------------------------------------------------------------
% Actual observed outcome:
% green = reuse empirically helped;
% red   = reuse empirically hurt.
% -------------------------------------------------------------------------

obsBenefit = ...
    validGeom & ...
    gObserved>0;

obsHarm = ...
    validGeom & ...
    gObserved<0;

obsNeutral = ...
    validGeom & ...
    gObserved==0;

hBenefit = scatter( ...
    axC, ...
    lambdaState(obsBenefit), ...
    wState(obsBenefit), ...
    24, ...
    'o', ...
    'filled', ...
    'MarkerFaceColor',green, ...
    'MarkerEdgeColor','w', ...
    'LineWidth',0.35, ...
    'DisplayName','Observed benefit');

hHarm = scatter( ...
    axC, ...
    lambdaState(obsHarm), ...
    wState(obsHarm), ...
    26, ...
    'o', ...
    'filled', ...
    'MarkerFaceColor',red, ...
    'MarkerEdgeColor','w', ...
    'LineWidth',0.35, ...
    'DisplayName','Observed harm');

if any(obsNeutral)

    hNeutral = scatter( ...
        axC, ...
        lambdaState(obsNeutral), ...
        wState(obsNeutral), ...
        24, ...
        'o', ...
        'filled', ...
        'MarkerFaceColor',grey, ...
        'MarkerEdgeColor','w', ...
        'LineWidth',0.35, ...
        'DisplayName','Observed neutral');

else

    hNeutral = gobjects(0);

end

% Outline the states for which the theory and observed benefit direction
% disagree. The 185-state frozen synthesis gives four such states.
misMask = ...
    validGeom & ...
    ~signConcordant;

if any(misMask)

    scatter( ...
        axC, ...
        lambdaState(misMask), ...
        wState(misMask), ...
        68, ...
        'o', ...
        'MarkerFaceColor','none', ...
        'MarkerEdgeColor',dgrey, ...
        'LineWidth',1.15, ...
        'HandleVisibility','off');

end

set( ...
    axC, ...
    'XScale','log', ...
    'XLim',[xMinC xMaxC], ...
    'YLim',[0 1], ...
    'FontName',FONT, ...
    'FontSize',FS_TICK, ...
    'TickDir','out', ...
    'LineWidth',0.75, ...
    'Box','off');

axC.XTickLabelRotation = 0;

xlabel( ...
    axC, ...
    'Evidence-admissibility coordinate, \Lambda', ...
    'FontName',FONT, ...
    'FontSize',FS_AXIS);

ylabel( ...
    axC, ...
    'Borrowing weight, w', ...
    'FontName',FONT, ...
    'FontSize',FS_AXIS);
ylim([0 0.2]);

text( ...
    axC, ...
    0.04,0.91, ...
    'reuse predicted to help', ...
    'Units','normalized', ...
    'HorizontalAlignment','left', ...
    'VerticalAlignment','top', ...
    'FontName',FONT, ...
    'FontSize',FS_TINY, ...
    'FontWeight','bold', ...
    'Color',green);

text( ...
    axC, ...
    0.98,0.91, ...
    {'reuse predicted' ...
    ' to hurt'}, ...
    'Units','normalized', ...
    'HorizontalAlignment','right', ...
    'VerticalAlignment','top', ...
    'FontName',FONT, ...
    'FontSize',FS_TINY, ...
    'FontWeight','bold', ...
    'Color',red);

text( ...
    axC, ...
    0.96,1.05, ...
    sprintf('sign agreement: %d/185',signN), ...
    'Units','normalized', ...
    'HorizontalAlignment','right', ...
    'VerticalAlignment','bottom', ...
    'FontName',FONT, ...
    'FontSize',FS_SMALL, ...
    'FontWeight','bold', ...
    'Color',green, ...
    'BackgroundColor','w');

if isempty(hNeutral)

    legend( ...
        axC, ...
        [hBenefit hHarm], ...
        {'Observed benefit','Observed harm'}, ...
        'Location','southwest', ...
        'Box','off', ...
        'FontName',FONT, ...
        'FontSize',6.8);

else

    legend( ...
        axC, ...
        [hBenefit hHarm hNeutral], ...
        {'Observed benefit','Observed harm','Observed neutral'}, ...
        'Location','southwest', ...
        'Box','off', ...
        'FontName',FONT, ...
        'FontSize',6.8);

end

