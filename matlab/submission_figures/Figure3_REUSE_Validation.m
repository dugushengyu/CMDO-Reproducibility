end

function tf = local_sign_concordance(a,b)

a = double(a(:));
b = double(b(:));

tf = false(size(a));

for i = 1:numel(a)

    if ~isfinite(a(i)) || ...
            ~isfinite(b(i))

        tf(i) = false;

    elseif a(i)==0 && b(i)==0

        tf(i) = true;

    elseif a(i)>0 && b(i)>0

        tf(i) = true;

    elseif a(i)<0 && b(i)<0

        tf(i) = true;

    end

end

end

function rho = local_spearman(x,y)

x = double(x(:));
y = double(y(:));

m = ...
    isfinite(x) & ...
    isfinite(y);

x = x(m);
y = y(m);

rx = local_tied_rank(x);
ry = local_tied_rank(y);

rx = rx-mean(rx);
ry = ry-mean(ry);

den = ...
    sqrt( ...
    sum(rx.^2) .* ...
    sum(ry.^2));

if den<=0

    rho = NaN;

else

    rho = ...
        sum(rx.*ry) ./ den;

end

end

function r = local_tied_rank(v)

v = double(v(:));

n = numel(v);

[sv,ord] = ...
    sort(v,'ascend');

r = zeros(n,1);

i = 1;

while i<=n

    j = i;

    while j<n && ...
            sv(j+1)==sv(i)

        j = j+1;

    end

    r(ord(i:j)) = ...
        0.5*(i+j);

    i = j+1;

end

end

