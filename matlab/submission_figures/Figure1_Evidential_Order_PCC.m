% A — REAL IMAGES
% ========================================================================
function draw_real_image_triplet(fig,ax,images,idx,r,S)

P = ax.Position;

labels = { ...
    'Dermoscopy', ...
    'Breast ultrasound', ...
    'Retinal fundus'};

gap = 0.010;
tw = (r(3)-2*gap)/3;

for k = 1:3
    rr = [ ...
        r(1)+(k-1)*(tw+gap), ...
        r(2), ...
        tw, ...
        r(4)];

    a = axes(fig,'Position',relpos(P,[ ...
        rr(1), ...
        rr(2)+0.11*rr(4), ...
        rr(3), ...
        0.72*rr(4)]));
    turn_off_toolbar(a);

    I = images(idx(k)).image;
    image(a,I);
    axis(a,'image');
    axis(a,'off');
    set(a,'YDir','reverse');

    rectangle(a, ...
        'Position',[0.5 0.5 size(I,2)-1 size(I,1)-1], ...
        'EdgeColor',[0.72 0.72 0.72], ...
        'LineWidth',0.7);

    text(ax,rr(1)+rr(3)/2,rr(2)+0.98*rr(4),labels{k}, ...
        'HorizontalAlignment','center', ...
        'FontName',S.font, ...
        'FontSize',F(S,6.6), ...
        'Color',S.text);
end

end

