%% ========================================================================
% CLEAR ARROW FOR PANEL C
% Robust shaft + explicit triangular arrowhead
% ========================================================================
function arrow_clear(ax,p1,p2,c,lw,headL,headW)

x1 = p1(1);
y1 = p1(2);

x2 = p2(1);
y2 = p2(2);

dx = x2-x1;
dy = y2-y1;

L = hypot(dx,dy);

if L <= eps
    return;
end

% Unit direction
ux = dx/L;
uy = dy/L;

% Do not let arrowhead become too large for a short arrow
headL = min(headL,0.30*L);

% Base of triangular head
xb = x2-headL*ux;
yb = y2-headL*uy;

% Perpendicular vector
px = -uy;
py =  ux;

% Shaft
plot( ...
    ax, ...
    [x1 xb], ...
    [y1 yb], ...
    '-', ...
    'Color',c, ...
    'LineWidth',lw, ...
    'Clipping','off');

% Explicit filled triangular head
patch( ...
    ax, ...
    [ ...
        x2, ...
        xb+headW*px, ...
        xb-headW*px], ...
    [ ...
        y2, ...
        yb+headW*py, ...
        yb-headW*py], ...
    c, ...
    'EdgeColor',c, ...
    'LineWidth',0.45, ...
    'Clipping','off');

end
