% LOAD FROZEN ASSETS — ROBUST PATH SEARCH
% ========================================================================
function [A, matPath] = load_frozen_assets(repoRoot)
thisFile = mfilename('fullpath');
if isempty(thisFile)
    scriptDir = pwd;
else
    scriptDir = fileparts(thisFile);
end

if nargin < 1 || isempty(repoRoot), repoRoot = fileparts(fileparts(scriptDir)); end
matPath = fullfile( ...
    repoRoot, ...
    'source_data', ...
    'figure1_assets', ...
    'Figure1_assets_selected_v1.mat');

assert(isfile(matPath), ...
    ['Missing tracked Figure 1 frozen asset:' newline matPath]);

q = whos('-file',matPath);
vars = string({q.name});
assert(any(vars=="Assets"), ...
    'Figure 1 MAT does not contain variable Assets.');

Q = load(matPath,'Assets');
A = Q.Assets;

assert(isfield(A,'images') && numel(A.images)>=4, ...
    'Assets.images is incomplete.');
assert(isfield(A,'tables') && numel(A.tables)>=1, ...
    'Assets.tables is incomplete.');
assert(isfield(A,'witnesses') && numel(A.witnesses)>=2, ...
    'Assets.witnesses is incomplete.');

fprintf('\n============================================================\n');
fprintf(' FIGURE 1 TRACKED FROZEN ASSET\n');
fprintf('============================================================\n');
fprintf('%s\n',matPath);
fprintf('============================================================\n\n');
end

