% A/B — FROZEN SCORE STREAM
% ========================================================================
function draw_score_stream(fig,ax,W,r,S,withTitle)

P = ax.Position;

a = axes(fig,'Position',relpos(P,r));
turn_off_toolbar(a);
hold(a,'on');

s = double(W.score(:));
n = numel(s);

take = unique(round(linspace(1,n,min(260,n))));
xx = 1:numel(take);
ss = s(take);

plot(a,xx,ss,'-', ...
    'Color',[0.48 0.48 0.48], ...
    'LineWidth',0.55);

scatter(a,xx,ss,7, ...
    'MarkerFaceColor',[0.36 0.36 0.36], ...
    'MarkerEdgeColor','none');

ylim(a,[0 1]);
xlim(a,[1 max(2,numel(xx))]);

set(a, ...
    'FontName',S.font, ...
    'FontSize',F(S,5.4), ...
    'Box','off', ...
    'TickDir','out', ...
    'XColor',S.axis, ...
    'YColor',S.axis, ...
    'YTick',[0 0.5 1]);

