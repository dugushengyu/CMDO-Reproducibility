function round_box(ax,p,face,edge,lw)
rectangle( ...
    ax, ...
    'Position',p, ...
    'Curvature',[0.04 0.04], ...
    'FaceColor',face, ...
    'EdgeColor',edge, ...
    'LineWidth',lw);
end

function arrow_norm(ax,p1,p2,c,lw)
quiver( ...
    ax, ...
    p1(1), p1(2), ...
    p2(1)-p1(1), p2(2)-p1(2), ...
    0, ...
    'Color',c, ...
    'LineWidth',lw, ...
    'MaxHeadSize',0.85);
end

function p = relpos(parentPos,r)
p = [ ...
    parentPos(1) + r(1)*parentPos(3), ...
    parentPos(2) + r(2)*parentPos(4), ...
    r(3)*parentPos(3), ...
    r(4)*parentPos(4)];
end

function turn_off_toolbar(ax)
try
    ax.Toolbar.Visible = 'off';
catch
end

try
    disableDefaultInteractivity(ax);
catch
end
end

