%% ========================================================================
% HELPERS
% ========================================================================

function hideToolbarSafe(ax)
try
    ax.Toolbar.Visible = 'off';
catch
    try
        axtoolbar(ax,{});
    catch
    end
end
end

function repoRoot = local_find_cmdo_repo(startDir)

repoRoot = '';
p = startDir;

for k = 1:8

    candidate = fullfile(p,'U10_Prospective_ECG');

    if isfolder(candidate)
        repoRoot = p;
        return;
    end

    parent = fileparts(p);

    if isempty(parent) || strcmp(parent,p)
        break;
    end

    p = parent;
end

end

function local_require_vars(T,vars,label)

missing = vars(~ismember(vars,T.Properties.VariableNames));

if ~isempty(missing)
    error('%s missing variables: %s', ...
        label, ...
        strjoin(missing,', '));
end

end
