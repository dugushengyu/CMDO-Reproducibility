fprintf('\nAdaptation frontier\n');
fprintf('H                  : %.8f\n',H);
fprintf('A                  : %.8f\n',A);
fprintf('C shared           : %.8f\n',Cshared);
fprintf('C pairing-disrupt  : %.8f\n',Cperm);
fprintf('C role-separated   : %.8f\n',Crole);

