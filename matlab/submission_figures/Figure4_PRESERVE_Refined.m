    'HorizontalAlignment','left', ...
    'VerticalAlignment','top', ...
    'FontName',FONT, ...
    'FontSize',8.8, ...
    'FontWeight','bold', ...
    'Color',DARK);

text(axB, ...
    costPerm+0.010,H+0.012, ...
    'pairing disrupted', ...
    'HorizontalAlignment','left', ...
    'VerticalAlignment','bottom', ...
    'FontName',FONT, ...
    'FontSize',8.6, ...
    'FontWeight','bold', ...
    'Color',PURPLE);

% Frontier label.
